#!/usr/bin/env python3
"""Generate seed_embed.hc: MemfsSeed() FileWrite()s for the AOT HolyC REPL."""
import os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
OUT = os.path.join(os.path.dirname(__file__), "seed_embed.hc")

# Curated memfs contents: small demos + key hc_repl sources for Src().
FILES = [
    ("hello.hc", None),  # synthetic below
    ("README.txt", None),
    ("uart.hc", "bootstrap/hc_repl/uart.hc"),
    ("fs.hc", "bootstrap/hc_repl/fs.hc"),
    ("dir.hc", "bootstrap/hc_repl/dir.hc"),
    ("eval.hc", "bootstrap/hc_repl/eval.hc"),
    ("jit.hc", "bootstrap/hc_repl/jit.hc"),
    ("start.hc", "bootstrap/hc_repl/start.hc"),
    ("repl.hc", "bootstrap/hc_repl/repl.hc"),
    ("mem.hc", "bootstrap/seed/mem.hc"),
    ("print.hc", "bootstrap/seed/print.hc"),
]

HELLO = r'''// hello.hc -- tiny memfs demo for Src/Dir
U0 Hello()
{
  "Hello from HolyC memfs\n";
}
'''

README = """HolyC AOT REPL
==============
Built on Mac by holyc-riscv into a RISC-V ELF.
Guest: UART, memfs, Print, MAlloc, Dir, Src, HolyC JIT — all HolyC.
Entry: asm{_start} in start.hc (no crt0.S). No 0x87001xxx host slots.
"""

def c_escape(s: str) -> str:
    return (s.replace("\\", "\\\\")
             .replace('"', '\\"')
             .replace("\n", "\\n")
             .replace("\t", "\\t")
             .replace("\r", "\\r"))

def body_for(name, rel):
    if name == "hello.hc":
        return HELLO
    if name == "README.txt":
        return README
    path = os.path.join(ROOT, rel)
    with open(path, encoding="utf-8") as f:
        return f.read()

def main():
    lines = [
        "// GENERATED by gen_embed.py — do not edit by hand.\n",
        "U0 MemfsSeed()\n{\n",
    ]
    for name, rel in FILES:
        body = body_for(name, rel)
        # Cap huge files so AOT data stays reasonable (str.hc is large).
        if len(body) > 12000:
            body = body[:12000] + "\n/* …truncated for embed… */\n"
        esc = c_escape(body)
        lines.append(f'  FileWrite("{name}", "{esc}", {len(body)});\n')
    lines.append("}\n")
    text = "".join(lines)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT} ({len(FILES)} files, {len(text)} bytes source)")

if __name__ == "__main__":
    main()
