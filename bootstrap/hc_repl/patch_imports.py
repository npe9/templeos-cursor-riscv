#!/usr/bin/env python3
"""Patch repl-holyc AOT import slots + g_trap_vec for trap entry.

QEMU -kernel loads the blob at 0x80000000 with no crt0 resolve_imports.
Import slots must hold absolute addresses; g_trap_vec is pre-filled for TrapInit.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

BLOB_BASE = 0x80000000
HOLY_IMPORT_MAGIC = 0x31504D4959464F48  # "HOFYIMP1" LE
TRAP_CTX_SAVE_SIG = struct.pack("<I", 0x10E00FB7) + struct.pack("<I", 0x003F9F93)  # lui t6,0x10e00; slli t6,t6,3

ASM_SIGS: dict[str, bytes] = {
    "TrapBareMtvec": struct.pack("<6I", 0x00800293, 0x3002B073, 0x30401073, 0x30551073, 0x0000100F, 0x00008067),
    "HcCsrrMcause": struct.pack("<2I", 0x34202573, 0x00008067),
    "HcCsrrMepc": struct.pack("<2I", 0x34102573, 0x00008067),
    "HcCsrrMtval": struct.pack("<2I", 0x34302573, 0x00008067),
    "HcCsrwMepc": struct.pack("<2I", 0x34151073, 0x00008067),
    "HcCsrsMieTimer": struct.pack("<3I", 0x00800293, 0x3042A073, 0x00008067),
    "HcCsrsMieExt": struct.pack("<4I", 0x000012B7, 0x8002829B, 0x3042A073, 0x00008067),
    "HcCsrsMstatusMie": struct.pack("<3I", 0x00800293, 0x3002A073, 0x00008067),
    "HcCsrrwMtvec": struct.pack("<3I", 0x30551073, 0x0000100F, 0x00008067),
    "ReplSetJmp": struct.pack("<I", 0x00053023),  # sd ra,0(a0) — first insn only
    "ReplLongJmp": struct.pack("<I", 0x00053083),  # ld ra,0(a0)
}


def parse_map(path: Path) -> dict[str, int]:
    syms: dict[str, int] = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        off_s, name = line.split(None, 1)
        if name.startswith("__imp_"):
            continue
        syms[name] = int(off_s, 16)
    return syms


def find_trap_vec_off(blob: bytes, syms: dict[str, int]) -> int:
    off = syms.get("TrapVec", 0)
    if off:
        return off
    pos = blob.find(TRAP_CTX_SAVE_SIG)
    if pos >= 4 and (struct.unpack_from("<I", blob, pos - 4)[0] & 0x7F) == 0x6F:
        return pos - 4
    return 0


def scan_sig(blob: bytes, sig: bytes) -> int:
    idx = blob.find(sig)
    return idx if idx >= 0 else 0


def resolve_off(name: str, syms: dict[str, int], blob: bytes, trap_vec: int) -> int:
    off = syms.get(name, 0)
    if off:
        return off
    sig = ASM_SIGS.get(name)
    if sig:
        off = scan_sig(blob, sig)
    if name == "TrapVec" and trap_vec:
        off = trap_vec
    return off


def patch_blob(blob_path: Path, map_path: Path, out_trap_hc: Path) -> int:
    blob = bytearray(blob_path.read_bytes())
    if len(blob) < 16:
        raise SystemExit(f"blob too small: {blob_path}")
    magic = struct.unpack_from("<Q", blob, len(blob) - 8)[0]
    count = struct.unpack_from("<Q", blob, len(blob) - 16)[0]
    if magic != HOLY_IMPORT_MAGIC:
        raise SystemExit(f"bad import magic {magic:#x} in {blob_path}")
    syms = parse_map(map_path)
    trap_vec = find_trap_vec_off(blob, syms)
    code_end = len(blob) - 16 - count * 32
    patched = 0
    missed: list[str] = []
    ent_off = len(blob) - 16 - count * 32
    for k in range(count):
        base = ent_off + k * 32
        slot = struct.unpack_from("<Q", blob, base)[0]
        name = bytes(blob[base + 8 : base + 32]).split(b"\0", 1)[0].decode()
        off = resolve_off(name, syms, blob, trap_vec)
        if not off or off >= code_end:
            missed.append(name)
            continue
        struct.pack_into("<Q", blob, slot, BLOB_BASE + off)
        patched += 1
    if trap_vec:
        gv = syms.get("g_trap_vec")
        if gv is not None:
            struct.pack_into("<Q", blob, gv, BLOB_BASE + trap_vec)
    blob_path.write_bytes(blob)
    out_trap_hc.write_text(
        f"// Generated by bootstrap/hc_repl/patch_imports.py — do not edit.\n"
        f"#define TRAP_VEC_OFF 0x{trap_vec:X}\n"
    )
    print(f"patched {patched}/{count} import slot(s); TRAP_VEC_OFF=0x{trap_vec:x}")
    if missed:
        print(f"unresolved ({len(missed)}): " + ", ".join(missed[:12]) + ("…" if len(missed) > 12 else ""))
    return patched


def main() -> None:
    if len(sys.argv) != 4:
        print(f"usage: {sys.argv[0]} <blob.bin> <repl.map> <trap_vec_off.hc>", file=sys.stderr)
        sys.exit(2)
    patch_blob(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))


if __name__ == "__main__":
    main()
