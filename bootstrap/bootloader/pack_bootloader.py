#!/usr/bin/env python3
"""Pack HolyC AOT bootloader (+ optional REPL payload) without GNU as/ld/objcopy.

  holyc-riscv boot.hc -o stub.bin   # flat machine code, _start at offset 0
  [copy mode] pad stub, append payload.bin
  [pflash]    zero-pad to PFLASH_SIZE

Product constraint: guest bootloader/REPL images are HolyC-only (host holyc-riscv
is the bootstrap compiler). See docs/BAREMETAL.md.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys


def trim_aot_trailing_zeros(data: bytes) -> bytes:
    """Drop AOT trailing zero padding; keep 8-byte alignment for copy loops."""
    i = len(data)
    while i > 0 and data[i - 1] == 0:
        i -= 1
    if i == 0:
        return data
    i = (i + 7) & ~7
    return data[:i]


def write_cfg(path: str, *, entry: int, boot_base: int, boot_copy: bool,
              payload_src: int, payload_end: int) -> None:
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by pack_bootloader.py — do not edit.\n")
        f.write(f"#define ENTRY_POINT 0x{entry:X}\n")
        f.write(f"#define BOOTLOADER_BASE 0x{boot_base:X}\n")
        # HolyC #if NAME is truthy when NAME is defined (value ignored) — use #ifdef.
        if boot_copy:
            f.write("#define BOOT_COPY 1\n")
        else:
            f.write("// BOOT_COPY undefined → jump mode\n")
        f.write(f"#define PAYLOAD_SRC 0x{payload_src:X}\n")
        f.write(f"#define PAYLOAD_END 0x{payload_end:X}\n")


def holyc_aot(holyc: str, src: str, out_bin: str, include_dir: str) -> None:
    env = os.environ.copy()
    # Relative #include "boot_cfg.hc" resolves next to boot.hc (src dir).
    env["HOLYC_INCLUDE_ROOT"] = include_dir
    holyc_abs = os.path.abspath(holyc)
    src_abs = os.path.abspath(src)
    out_abs = os.path.abspath(out_bin)
    cmd = [holyc_abs, src_abs, "-o", out_abs]
    r = subprocess.run(cmd, cwd=include_dir, env=env, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout or "")
        sys.stderr.write(r.stderr or "")
        raise SystemExit(f"error: holyc-riscv failed for {src}")


def pad_to(data: bytes, size: int) -> bytes:
    if len(data) > size:
        raise SystemExit(f"error: image {len(data)} exceeds pad size {size}")
    if len(data) == size:
        return data
    return data + bytes(size - len(data))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--holyc", required=True, help="path to holyc-riscv")
    ap.add_argument("--src-dir", required=True, help="bootstrap/bootloader/")
    ap.add_argument("--out", required=True, help="output boot.bin")
    ap.add_argument("--mode", choices=("jump", "copy"), default="jump")
    ap.add_argument("--entry-point", default="0x80000000")
    ap.add_argument("--bootloader-base", default="0x20000000")
    ap.add_argument("--payload", default="", help="flat REPL/kernel .bin (copy mode)")
    ap.add_argument("--pflash-size", default="0", help="pad output to this size (0=off)")
    ap.add_argument("--header-align", type=int, default=64,
                    help="min aligned stub region before payload (copy mode)")
    args = ap.parse_args()

    entry = int(args.entry_point, 0)
    boot_base = int(args.bootloader_base, 0)
    pflash = int(args.pflash_size, 0) if args.pflash_size else 0
    src_dir = os.path.abspath(args.src_dir)
    boot_hc = os.path.join(src_dir, "boot.hc")
    cfg_hc = os.path.join(src_dir, "boot_cfg.hc")
    out_bin = os.path.abspath(args.out)
    os.makedirs(os.path.dirname(out_bin) or ".", exist_ok=True)

    stub_path = out_bin + ".stub"
    # Pass 1: jump stub (or copy stub with placeholder addrs) to measure size.
    write_cfg(
        cfg_hc,
        entry=entry,
        boot_base=boot_base,
        boot_copy=(args.mode == "copy"),
        payload_src=boot_base + args.header_align,
        payload_end=boot_base + args.header_align,
    )
    holyc_aot(args.holyc, boot_hc, stub_path, src_dir)
    with open(stub_path, "rb") as f:
        stub = trim_aot_trailing_zeros(f.read())

    if args.mode == "jump":
        image = stub
        if pflash:
            image = pad_to(image, pflash)
        with open(out_bin, "wb") as f:
            f.write(image)
        try:
            os.remove(stub_path)
        except OSError:
            pass
        print(f"✓ HolyC bootloader (jump) {len(image)} bytes → {out_bin}")
        print(f"  ENTRY_POINT=0x{entry:X} BOOTLOADER_BASE=0x{boot_base:X}")
        return 0

    if not args.payload:
        raise SystemExit("error: --payload required for copy mode")
    with open(args.payload, "rb") as f:
        payload = f.read()
    # Pad payload to 8 bytes for ld/sd copy loop.
    if len(payload) % 8:
        payload = payload + bytes(8 - (len(payload) % 8))

    hdr = max(args.header_align, (len(stub) + 7) & ~7)
    if len(stub) > hdr:
        raise SystemExit(f"error: stub {len(stub)} exceeds header align {hdr}")

    payload_src = boot_base + hdr
    payload_end = payload_src + len(payload)
    # Pass 2: re-AOT with real PAYLOAD_SRC / PAYLOAD_END.
    write_cfg(
        cfg_hc,
        entry=entry,
        boot_base=boot_base,
        boot_copy=True,
        payload_src=payload_src,
        payload_end=payload_end,
    )
    holyc_aot(args.holyc, boot_hc, stub_path, src_dir)
    with open(stub_path, "rb") as f:
        stub = trim_aot_trailing_zeros(f.read())
    if len(stub) > hdr:
        raise SystemExit(f"error: copy stub {len(stub)} exceeds header {hdr}")

    image = pad_to(stub, hdr) + payload
    if pflash:
        image = pad_to(image, pflash)
    with open(out_bin, "wb") as f:
        f.write(image)
    try:
        os.remove(stub_path)
    except OSError:
        pass
    print(f"✓ HolyC bootloader (copy) {len(image)} bytes → {out_bin}")
    print(f"  stub={len(stub)} hdr={hdr} payload={len(payload)} "
          f"ENTRY_POINT=0x{entry:X}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
