#!/usr/bin/env python3
"""Build the REPL boot runtime snapshot (concatenated HolyC seeds).

Boot embeds this blob and run_source()s it once instead of Run()ing each seed.
Edit individual bootstrap/seed/*.hc, then:

  make repl-blob

which rewrites bootstrap/boot_blob_embed.h and validates with holyc-riscv AOT.
"""
from __future__ import annotations

import os
import subprocess
import sys

# Must match BootHolyCRuntime / worry_dream_repl.c boot order.
BOOT_ORDER = [
    "MemMapSelected.hc",  # Kconfig MEM_* (syncconfig); must precede uart.hc / csr.hc
    "uart.hc",
    "mem.hc",
    "print.hc",
    "str.hc",
    "log.hc",
    "frame.hc",  # after log (redefines LogMuxEmit); g_uart_mux from uart.hc
    "console.hc",  # soft VT mux (CONSOLE.md #4); after frame for VtMuxNotify
    "tty.hc",  # CONSOLE.md #1 line discipline (after uart PutCh)
    "fs.hc",
    "run.hc",
    "math.hc",
    "term.hc",
    "sym.hc",
    "csr.hc",
    "ds.hc",
    "ds_csr.hc",
    "ds_uart.hc",
    "ds_clint.hc",
    "ds_plic.hc",
    "fmt.hc",
    "ninep.hc",
    "dir.hc",
    "asm_complete.hc",
    # asm_doc.hc: large tables — still gated (templates via asm_templates.inc)
    "complete.hc",
    "ed.hc",
    "edit.hc",
    "start.hc",
    "trap.hc",
    "debug.hc",
    "hwdbg.hc",
    "gdbstub.hc",
    "disasm.hc",
    "vim.hc",
    "RVEditorSelected.hc",
    "man.hc",
    "files.hc",
    "zmodem.hc",
    "trzsz.hc",
    "funs.hc",
    "callers.hc",
    "sys.hc",
    "ops.hc",
    "boot.hc",
]


def esc_c(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
        .replace("\r", "\\r")
    )


def seed_path(seed_dir: str, name: str) -> str:
    """Resolve a boot seed: top-level seed/ first, then seed/datasheet/."""
    p = os.path.join(seed_dir, name)
    if os.path.isfile(p):
        return p
    p = os.path.join(seed_dir, "datasheet", name)
    if os.path.isfile(p):
        return p
    return os.path.join(seed_dir, name)


def read_asm_doc_raw(seed_dir: str) -> str:
    """Concatenate HolyC string literals assigned to AsmDocRaw in asm_doc.hc."""
    path = seed_path(seed_dir, "asm_doc.hc")
    text = open(path, encoding="utf-8").read()
    key = "AsmDocRaw"
    i = text.find(key)
    if i < 0:
        return ""
    i = text.find("=", i)
    if i < 0:
        return ""
    parts: list[str] = []
    while i < len(text):
        q = text.find('"', i)
        if q < 0:
            break
        q2 = text.find('"', q + 1)
        if q2 < 0:
            break
        parts.append(text[q + 1 : q2])
        i = q2 + 1
        rest = text[i:].lstrip()
        if rest.startswith(";"):
            break
        if not rest.startswith('"'):
            break
    return "".join(parts)


def repo_root(seed_dir: str) -> str:
    """Repo root: parent of bootstrap/ (seed_dir is typically bootstrap/seed)."""
    bootstrap = os.path.abspath(os.path.join(seed_dir, ".."))
    return os.path.abspath(os.path.join(bootstrap, ".."))


def gen_asm_templates_inc(seed_dir: str, out_path: str) -> None:
    """Emit mn|template pairs for worry_dream_repl.c Tab hints (from asm_doc.hc)."""
    raw = read_asm_doc_raw(seed_dir)
    pairs: list[str] = []
    for rec in raw.split(";"):
        rec = rec.strip()
        if not rec:
            continue
        fields = rec.split("|")
        if len(fields) >= 2 and fields[0] and fields[1]:
            pairs.append(fields[0])
            pairs.append(fields[1])
    body = "|".join(pairs)
    esc = body.replace("\\", "\\\\").replace('"', '\\"')
    hdr = [
        "// GENERATED by bootstrap/gen_boot_blob.py from seed/asm_doc.hc — do not edit.\n",
        f'static const char rl_asm_tpl_raw[] = "{esc}";\n',
    ]
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    open(out_path, "w", encoding="utf-8").write("".join(hdr))
    print(f"wrote {out_path} ({len(pairs) // 2} templates)")


def main() -> int:
    if len(sys.argv) < 3:
        print(
            "usage: gen_boot_blob.py <seed_dir> <out_embed.h> [holyc-riscv] [out.bin]",
            file=sys.stderr,
        )
        return 2
    seed_dir, out_h = sys.argv[1], sys.argv[2]
    holyc = sys.argv[3] if len(sys.argv) > 3 else None
    out_bin = sys.argv[4] if len(sys.argv) > 4 else None

    parts: list[str] = [
        "// GENERATED by bootstrap/gen_boot_blob.py — do not edit.\n",
        "// Snapshot of HolyC seeds in boot order. Rebuild: make repl-blob\n",
    ]
    for name in BOOT_ORDER:
        path = seed_path(seed_dir, name)
        if not os.path.isfile(path):
            print(f"error: missing seed {path}", file=sys.stderr)
            return 1
        body = open(path, encoding="utf-8").read()
        if not body.endswith("\n"):
            body += "\n"
        parts.append(f"\n// ##### BEGIN {name} #####\n")
        parts.append(body)
        parts.append(f"// ##### END {name} #####\n")
    blob = "".join(parts)

    # Optional AOT validation / artifact (future Load target).
    if holyc:
        root = repo_root(seed_dir)
        hc_path = os.path.join(os.path.dirname(out_h) or ".", "boot_runtime.hc")
        os.makedirs(os.path.dirname(hc_path) or ".", exist_ok=True)
        open(hc_path, "w", encoding="utf-8").write(blob)
        bin_path = out_bin or os.path.join(os.path.dirname(out_h) or ".", "boot_runtime.bin")
        env = os.environ.copy()
        env["HOLYC_INCLUDE_ROOT"] = root
        r = subprocess.run(
            [holyc, hc_path, "-o", bin_path],
            capture_output=True,
            text=True,
            env=env,
        )
        if r.returncode != 0 or "Error:" in (r.stdout + r.stderr):
            sys.stderr.write(r.stdout)
            sys.stderr.write(r.stderr)
            print("error: holyc-riscv failed to AOT-validate boot blob", file=sys.stderr)
            return 1
        print(f"validated AOT blob → {bin_path} ({os.path.getsize(bin_path)} bytes)")

    hdr = [
        "// GENERATED by bootstrap/gen_boot_blob.py — do not edit.\n",
        "// Prebuilt HolyC boot runtime snapshot. Rebuild: make repl-blob\n",
        "static const char repl_boot_blob[] =\n",
        f'  "{esc_c(blob)}";\n',
    ]
    open(out_h, "w", encoding="utf-8").write("".join(hdr))
    gen_asm_templates_inc(seed_dir, os.path.join(os.path.dirname(out_h) or ".", "asm_templates.inc"))
    print(f"wrote {out_h} ({len(blob)} source bytes, {len(BOOT_ORDER)} seeds)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
