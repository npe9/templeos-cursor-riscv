#!/usr/bin/env python3
"""Generate Kernel/RVCmpImports.HC — HashAdd all Compiler.BIN IET_IMM_I64 names.
Also emit Kernel/RVCmpRtPatch.HH with data-section offsets for Fs/adam_task (from HOLYC_MAP)."""
from pathlib import Path
import struct
import os
import re

root = Path(__file__).resolve().parents[1]
bin_path = root / "build" / "Compiler.BIN"
out = root / "Kernel" / "RVCmpImports.HC"
rt_out = root / "Kernel" / "RVCmpRtPatch.HH"
map_path = Path(os.environ.get("HOLYC_MAP", str(root / "build" / "compiler_rv.map")))

# _intern ops have no jalr entry; export RV* wrappers from KCmpStubsRV.HC instead.
INTERN_WRAPPERS = {
    "Bt": "RVBt",
    "Bts": "RVBts",
    "Btr": "RVBtr",
    "LBts": "RVLBts",
    "LBtr": "RVLBtr",
    "Bsf": "RVBsf",
    "Bsr": "RVBsr",
    "ToUpper": "RVToUpper",
    "StrLen": "RVStrLen",
    "MaxI64": "RVMaxI64",
    "MinI64": "RVMinI64",
    "QueInit": "RVQueInit",
    "QueIns": "RVQueIns",
    "QueRem": "RVQueRem",
    "SwapI64": "RVSwapI64",
    "MemSet": "RVMemSet",
    "MemCpy": "RVMemCpy",
    "MemSetI64": "RVMemSetI64",
    "StrCmp": "RVStrCmp",
    "StrCpy": "RVStrCpy",
    "ClampI64": "RVClampI64",
    "BEqu": "RVBEqu",
    "StrIMatch": "RVStrIMatch",
    "Call": "RVCall",
}

if not bin_path.exists():
    raise SystemExit(f"missing {bin_path} — run pack_tosb first")

b = bin_path.read_bytes()
pto = struct.unpack_from("<q", b, 16)[0]
i = pto
names = []
while i < len(b):
    et = b[i]
    i += 1
    if et == 0:
        break
    i += 4  # u32 off
    start = i
    while i < len(b) and b[i]:
        i += 1
    name = b[start:i].decode("ascii")
    i += 1
    if et == 11 and name not in names:
        names.append(name)

lines = [
    "// AUTO-GENERATED by tools/gen_cmp_imports.py — export guest addrs for Load(Compiler.BIN).",
    f"// {len(names)} unique IET_IMM_I64 import names from build/Compiler.BIN.",
    "",
    "U0 RVCmpExportOne(U8 *name,I64 addr)",
    "{",
    "  CHashExport *e;",
    "  if (!name || !addr) return;",
    "  if (HashFind(name,Fs->hash_table,HTT_EXPORT_SYS_SYM))",
    "    return;",
    "  e=CAlloc(sizeof(CHashExport));",
    "  e->type=HTT_EXPORT_SYS_SYM|HTF_IMM;",
    "  e->str=StrNew(name);",
    "  e->val=addr;",
    "  HashAdd(e,Fs->hash_table);",
    "}",
    "",
    "I64 RVCmpExportImports()",
    "{//Register kernel/Body symbols so Load() can patch Compiler.BIN IMM_I64 slots.",
    "  I64 n=0;",
]
for name in sorted(names):
    sym = INTERN_WRAPPERS.get(name, name)
    lines.append(f'  RVCmpExportOne("{name}",&{sym}); n++;')
lines += [
    "  return n;",
    "}",
    "",
]
out.write_text("\n".join(lines))

fs_off = adam_off = gs_off = blkdev_off = None
char_bmps = {}
CHAR_BMP_NAMES = [
    "char_bmp_alpha",
    "char_bmp_alpha_numeric",
    "char_bmp_alpha_numeric_no_at",
    "char_bmp_word",
    "char_bmp_dec_numeric",
    "char_bmp_hex_numeric",
    "char_bmp_white_space",
    "char_bmp_non_eol_white_space",
    "char_bmp_zero_cr_nl_cursor",
    "char_bmp_zero_tab_cr_nl_cursor",
    "char_bmp_zero_tab_cr_nl_cursor_dollar",
    "char_bmp_macro",
    "char_bmp_printable",
    "char_bmp_displayable",
    "char_bmp_safe_dollar",
    "char_bmp_filename",
    "char_bmp_non_eol",
]
if map_path.exists():
    for line in map_path.read_text().splitlines():
        m = re.match(r"^([0-9a-fA-F]+)\s+(\S+)$", line.strip())
        if not m:
            continue
        off, sym = int(m.group(1), 16), m.group(2)
        if sym == "Fs":
            fs_off = off
        elif sym == "adam_task":
            adam_off = off
        elif sym == "Gs":
            gs_off = off
        elif sym == "blkdev":
            blkdev_off = off
        elif sym in CHAR_BMP_NAMES:
            char_bmps[sym] = off
rt_lines = [
    "// AUTO-GENERATED by tools/gen_cmp_imports.py from compiler_rv.map",
    "// Offsets of runtime globals inside host-AOT Compiler.BIN image (module_base+off).",
    f"#define RV_CMP_FS_OFF\t\t0x{(fs_off or 0):x}",
    f"#define RV_CMP_ADAM_TASK_OFF\t0x{(adam_off or 0):x}",
    f"#define RV_CMP_GS_OFF\t\t0x{(gs_off or 0):x}",
    f"#define RV_CMP_BLKDEV_OFF\t0x{(blkdev_off or 0):x}",
    "",
]
for n in CHAR_BMP_NAMES:
    macro = "RV_CMP_" + n.upper() + "_OFF"
    rt_lines.append(f"#define {macro}\t0x{char_bmps.get(n, 0):x}")
rt_lines += [
    "",
    "U0 RVCmpPatchCharBmps(U8 *mod)",
    "{//Host-AOT Compiler.BIN keeps zeroed char_bmp_*; Lex needs kernel bitmaps.",
    "  if (!mod) return;",
]
for n in CHAR_BMP_NAMES:
    macro = "RV_CMP_" + n.upper() + "_OFF"
    rt_lines.append(f"  if ({macro}) MemCpy(mod+{macro},{n},16*sizeof(U32));")
rt_lines += ["}", ""]
rt_out.write_text("\n".join(rt_lines))
print(f"gen_cmp_imports: {len(names)} → {out} (wrappers={len(INTERN_WRAPPERS)})")
print(f"gen_cmp_imports: Fs={fs_off} adam_task={adam_off} Gs={gs_off} blkdev={blkdev_off} char_bmps={len(char_bmps)} → {rt_out}")
