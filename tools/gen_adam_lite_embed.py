#!/usr/bin/env python3
"""Stage in-tree Adam/Menu_RV_Guest*.HC for phase3 guest Cmp (G9 - no full Menu U8[]).

Reads Adam/Menu_RV_Guest.HC (+ optional Guest_Lex) and emits Kernel/RVAdamLiteMenuSrc.HC:
  - RVAdamLiteMenuGuestSrc() - body of Menu_RV_Guest.HC
  - RVAdamLiteMenuRVWrapSrc() - #define MENU_RV_GUEST_CMP + #include Menu_RV_Guest
  - RVAdamLiteMenuLexSrc() - index hand Lex probe (not nested into AdamLite)

HolyC return of bare adjacent string literals may keep only the first chunk;
assign to a local U8* first so concat is visible to FileWrite/StrLen.
"""
from __future__ import annotations

import pathlib


def c_string_chunks(data: str, width: int = 60) -> str:
    esc = (
        data.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\0", "\\0")
    )
    lines = esc.split("\n")
    parts: list[str] = []
    for i, line in enumerate(lines):
        chunk = line + ("\\n" if i < len(lines) - 1 or data.endswith("\n") else "")
        while chunk:
            piece, chunk = chunk[:width], chunk[width:]
            parts.append(f'"{piece}"')
    if not parts:
        parts = ['""']
    return "\n    ".join(parts)


root = pathlib.Path(__file__).resolve().parents[1]
guest = (root / "Adam" / "Menu_RV_Guest.HC").read_text()
lex = (root / "Adam" / "Menu_RV_Guest_Lex.HC").read_text()
out_hc = root / "Kernel" / "RVAdamLiteMenuSrc.HC"
stub = root / "Kernel" / "RVAdamLiteEmbed.HC"

# Lex before Guest so MENU_RV_GUEST_LEX_HC is set and Init can RVMenuLexNew.
wrap = (
    '#define MENU_RV_GUEST_CMP 1\n'
    '#include "Menu_RV_Guest_Lex"\n'
    '#include "Menu_RV_Guest"\n'
)

out_hc.write_text(
    "// AUTO-GENERATED by tools/gen_adam_lite_embed.py - do not edit.\n"
    "// In-tree Adam/Menu_RV_Guest*.HC staged as RedSea strings (not full Menu_RV U8[]).\n"
    "U8 *RVAdamLiteMenuGuestSrc()\n"
    "{\n"
    "  U8 *s;\n"
    f"  s =\n    {c_string_chunks(guest)};\n"
    "  return s;\n"
    "}\n"
    "\n"
    "U8 *RVAdamLiteMenuRVWrapSrc()\n"
    "{\n"
    "  U8 *s;\n"
    f"  s =\n    {c_string_chunks(wrap)};\n"
    "  return s;\n"
    "}\n"
    "\n"
    "U8 *RVAdamLiteMenuLexSrc()\n"
    "{\n"
    "  U8 *s;\n"
    f"  s =\n    {c_string_chunks(lex)};\n"
    "  return s;\n"
    "}\n"
)

stub.write_text(
    "// AUTO-GENERATED by tools/gen_adam_lite_embed.py - G9 residual shrink.\n"
    "// Menu staging: Kernel/RVAdamLiteMenuSrc.HC from Adam/Menu_RV_Guest*.HC.\n"
    "// Soft P6: guest Cmp `#include Menu_RV` -> Lex+Guest -> AdamLite.BIN.\n"
    "// Wrap folds Guest_Lex before Guest; flat Guest alone still no Lex.\n"
    "// Full Menu_RV.HC CMenu/CmpCtrl still host/WinMgr (not MENU_RV_GUEST_CMP).\n"
    "I64 rv_adam_lite_embed_stub = 1;\n"
)

print(f"gen_adam_lite_embed: Menu_RV_Guest -> {out_hc} ({len(guest)} bytes guest)")
print(f"gen_adam_lite_embed: Menu_RV_Guest_Lex ({len(lex)} bytes)")
print(f"gen_adam_lite_embed: stub -> {stub}")
