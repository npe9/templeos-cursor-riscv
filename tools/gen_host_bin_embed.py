#!/usr/bin/env python3
"""Pack tiny AOT probe as TOSB and emit Kernel/RVHostBinEmbed.HC."""
import pathlib, subprocess, sys
root = pathlib.Path(__file__).resolve().parents[1]
pack = root / 'tools' / 'pack_tosb'
hc = root / 'holyc-riscv'
out_hc = root / 'Kernel' / 'RVHostBinEmbed.HC'
blob = root / 'build' / 'rv_cmp_probe.blob.bin'
tosb = root / 'build' / 'rv_cmp_probe.BIN'
probe = root / 'build' / 'rv_cmp_probe.hc'
root.joinpath('build').mkdir(exist_ok=True)
probe.write_text('I64 RVCmpProbe()\n{\n  return 7;\n}\n')
subprocess.check_call([str(hc), str(probe), '-o', str(blob)], stdout=subprocess.DEVNULL)
subprocess.check_call([str(pack), '-e', 'RVCmpProbe:0', str(blob), str(tosb)])
b = tosb.read_bytes()
# Emit the `holyc-riscv --fmt` canonical shape directly (single-line initializer,
# `, ` separators, spaces around `=`) so `make fmt-check` stays green after every
# regeneration — see tests/scripts/holyc_fmt_paths.sh.
lines = [
  '// AUTO-GENERATED by tools/gen_host_bin_embed.py — host-packed TOSB for Load().',
  '// Tiny AOT probe (RVCmpProbe→7). Full Compiler.BIN is build/Compiler.BIN via pack_tosb.',
  f'U8 rv_host_bin[{len(b)}] = {{' + ', '.join(f'0x{x:02X}' for x in b) + '};',
  f'I64 rv_host_bin_size = {len(b)};',
  '',
]
out_hc.write_text('\n'.join(lines))
print(f'gen_host_bin_embed: {len(b)} bytes → {out_hc}')
