#!/usr/bin/env python3
"""Generate Kernel/DemoAPI.HH — the kernel surface stock Demo/ programs name.

Why: a demo has to be compilable as its OWN unit (kernel headers, no kernel bodies) so its
globals cannot collide with the kernel's. Demo/Games/Maze.HC declares `U32 text[][]`, which
lands on the kernel's `CTextGlbls text;` when both are built into one blob and re-aims every
offset the kernel already compiled. Compiled separately, the kernel symbols a demo names
become imports resolved at Load — the Compiler.BIN model.

Pipeline, all of it measured rather than hand-listed:
  1. compile every Demo/**/*.HC standalone, with HOLYC_ALL_ERRORS
  2. collect every `Undefined variable 'X'`
  3. keep the X that are PRESENT in a kernel map (the rest are not implemented yet)
  4. emit `public extern` for each, read from the definition in the files Kernel_RV.PRJ compiles

Discovery is iterative — declaring one layer reveals the next — so it runs to a fixed point.

    tools/gen_demo_api.py [--jobs N] [--rounds N]
"""
import argparse, os, pathlib, re, subprocess, sys, tempfile
from concurrent.futures import ThreadPoolExecutor

ROOT = pathlib.Path(__file__).resolve().parents[1]
HDR = ROOT / "Kernel" / "DemoAPI.HH"
TYPE = r"(?:U0|I0|Bool|U8|I8|U16|I16|U32|I32|U64|I64|F64|C[A-Za-z0-9_]+)"
PRELUDE = """#include "/Kernel/KernelA.HH"
#exe {Option(OPTf_EXTERNS_TO_IMPORTS,ON);};
#include "/Kernel/KernelB.HH"
#include "/Kernel/KernelC.HH"
#include "/Kernel/RVGr.HH"
#exe {Option(OPTf_EXTERNS_TO_IMPORTS,OFF);};
#define RV_NO_DEMO_AUTORUN
"""

def prj_sources():
    """The files Kernel_RV.PRJ actually compiles — a definition anywhere else is not in the image."""
    out = []
    for m in re.finditer(r'#include "([^"]+)"', (ROOT / "Kernel" / "Kernel_RV.PRJ").read_text(errors="replace")):
        inc = m.group(1)
        for p in (ROOT / "Kernel" / (inc + ".HC"), ROOT / (inc.lstrip("/") + ".HC")):
            if p.exists():
                out.append(p)
                break
    return out

def kernel_symbols():
    """Names present in a built kernel image, via HOLYC_MAP."""
    with tempfile.NamedTemporaryFile(suffix=".map", delete=False) as t:
        mp = t.name
    env = dict(os.environ, HOLYC_NO_TIER2="1", HOLYC_MAP=mp, HOLYC_INCLUDE_ROOT=str(ROOT))
    subprocess.run([str(ROOT / "holyc-riscv"), str(ROOT / "tests/exec/cases/kernel_fb_demo.hc"),
                    "-o", os.devnull], env=env, capture_output=True)
    syms = set()
    for line in open(mp, errors="replace"):
        f = line.split()
        if len(f) >= 2:
            syms.add(f[1])
    os.unlink(mp)
    return syms

def undefined_in(args):
    """Probe with the declarations found SO FAR injected inline — never by including the
    generated header, or a second run sees nothing undefined and wipes the file."""
    demo, sofar = args
    src = PRELUDE + "\n".join(sofar) + '\n#include "/%s"\nI64 DemoProbe() { return 1; }\n' % demo
    with tempfile.NamedTemporaryFile("w", suffix=".hc", delete=False) as t:
        t.write(src)
        path = t.name
    env = dict(os.environ, HOLYC_ALL_ERRORS="1", HOLYC_NO_TIER2="1", HOLYC_INCLUDE_ROOT=str(ROOT))
    r = subprocess.run([str(ROOT / "holyc-riscv"), path, "-o", os.devnull], env=env, capture_output=True)
    os.unlink(path)
    txt = (r.stdout + r.stderr).decode("utf-8", "replace")
    return set(re.findall(r"Undefined variable '([A-Za-z0-9_]+)'", txt))

def alias_define(sym, srcs):
    """`#define DCFill RVDCFill` — the kernel exports the RV* name and stock code calls the
    stock one. A header of externs alone cannot express that; carry the define."""
    pat = re.compile(r"^#define\s+%s\s+([A-Za-z_][A-Za-z0-9_]*)\s*$" % re.escape(sym), re.M)
    for p in srcs:
        m = pat.search(p.read_text(errors="replace"))
        if m:
            return "#define %s %s" % (sym, m.group(1)), m.group(1), p
    return None, None, None

def declaration(sym, srcs):
    fn = re.compile(r"^(?:public\s+)?(%s\s*\**)\s*%s\s*\(([^;{]*)\)\s*(?:\{|$)" % (TYPE, re.escape(sym)), re.M)
    gl = re.compile(r"^(?:public\s+)?(%s\s*\**)\s*%s\s*(?:=[^;]*)?;" % (TYPE, re.escape(sym)), re.M)
    for p in srcs:
        txt = p.read_text(errors="replace")
        m = fn.search(txt)
        if m:
            return "public extern %s %s(%s);" % (m.group(1).strip(), sym, " ".join(m.group(2).split())), p
        m = gl.search(txt)
        if m:
            return "public extern %s %s;" % (m.group(1).strip(), sym), p
    return None, None

def write_header(decls, defines, stats):
    L = [
        "// Kernel/DemoAPI.HH — the kernel surface stock Demo/ programs name.",
        "//",
        "// GENERATED by tools/gen_demo_api.py. Do not hand-edit: it is read from the definitions in",
        "// the files Kernel_RV.PRJ compiles, so it cannot drift from what the kernel exports.",
        "//",
        "// It exists so a demo compiles as its OWN unit — kernel headers, no kernel bodies — with",
        "// these resolved as imports at Load (the Compiler.BIN model). Built as one blob instead, a",
        "// demo global lands on a kernel global of the same name: Demo/Games/Maze.HC's",
        "// `U32 text[][]` hits `CTextGlbls text;` and re-aims every offset the kernel compiled.",
        "//",
        "// Census over %d Demo programs: %d distinct kernel symbols named, %d present in the image"
        % (stats["demos"], stats["named"], len(decls)),
        "// and declared here. The remainder are not implemented yet, so they cannot be declared.",
        "#ifndef DEMO_API_HH",
        "#define DEMO_API_HH",
        "",
        "// The graphics TYPES, so `gr.field` and `dc->field` resolve. Without them the compiler",
        "// forward-declares an opaque class and every member access is an error.",
        '#include "RVGr.HH"',
        "",
    ]
    for d in sorted(set(defines)):
        L.append(d)
    if defines:
        L.append("")
    for sym, decl, src in sorted(decls):
        L.append("%-92s //%s" % (decl, src))
    L += ["", "#endif", ""]
    HDR.write_text("\n".join(L))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--rounds", type=int, default=4)
    a = ap.parse_args()
    demos = sorted(str(p.relative_to(ROOT)) for p in ROOT.glob("Demo/**/*.HC"))
    srcs = prj_sources()
    kern = kernel_symbols()
    decls, seen, defines = [], set(), []
    for rnd in range(1, a.rounds + 1):
        with ThreadPoolExecutor(a.jobs) as ex:
            sofar = [d for _, d, _ in decls] + defines
            res = list(ex.map(undefined_in, [(d, sofar) for d in demos]))
        named = set().union(*res) if res else set()
        new = [s for s in sorted(named & kern) if s not in seen]
        print("round %d: %d demos, %d undefined, %d in kernel, %d new"
              % (rnd, len(demos), len(named), len(named & kern), len(new)))
        if not new and not [x for x in (named - kern) if x not in seen and alias_define(x, srcs)[0]]:
            break
        for s in new:
            d, p = declaration(s, srcs)
            if d:
                decls.append((s, d, p.relative_to(ROOT)))
                seen.add(s)
        for s in sorted(named - kern):
            if s in seen:
                continue
            adef, target, p = alias_define(s, srcs)
            if adef and target in kern:
                tdecl, tp = declaration(target, srcs)
                if tdecl and target not in seen:
                    decls.append((target, tdecl, tp.relative_to(ROOT)))
                    seen.add(target)
                defines.append(adef)
                seen.add(s)
    write_header(decls, defines, {"demos": len(demos), "named": len(named)})
    print("wrote %s: %d declarations, %d defines" % (HDR.relative_to(ROOT), len(decls), len(defines)))

main()
