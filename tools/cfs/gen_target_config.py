#!/usr/bin/env python3
"""Do CMake's job for cFE's target configuration: GLOBAL_CONFIGDATA and GLOBAL_CFE_CONFIGDATA.

WHY THIS EXISTS. cFE's build generates a per-target configuration object that the flight code
reads at runtime. It is not in the source tree:

  - `vendor/cFE/cmake/target/src/target_config.c` instantiates `Target_ConfigData
    GLOBAL_CONFIGDATA`, but every table it points at (CFE_CORE_MODULE_LIST,
    CFE_BUILD_ENV_TABLE, CFE_MODULE_VERSION_TABLE, CFE_PSP_MODULE_LIST,
    CFE_CORE_MODULE_OBJTAB, CFE_STATIC_APP_LIST) is emitted by CMake per target.
  - `GLOBAL_CFE_CONFIGDATA` likewise, carrying the mount points and memory sizes.

Two modules already need it and every remaining one will:

    cfe_fs_api.c         GetDefaultMountPoint reads NonvolMountPoint / RamdiskMountPoint,
                         GetDefaultExtension reads Default_ModuleExtension
    cfe_config_init.c    reads MissionName, ModuleVersionList, CoreModuleList, StaticAppList,
                         BuildEnvironment, EdsDb, SbIntfDb, TaAffinityTable

This emits BOTH halves from one set of values -- the C for the differential oracle and the
HolyC for the translation -- exactly as gen_osconfig.py does, so the two sides cannot disagree
about a mount point and leave the transcript to find out somewhere far away.

THE VALUES ARE PORT DECISIONS, not NASA's. A real mission supplies them through CMake. They are
written down here, in one place, rather than scattered: this is a TempleOS/RISC-V target, its
modules are .BIN files, and its two mount points are the ones this port actually has.

    tools/cfs/gen_target_config.py <outdir>
"""
import os
import sys

# --- the port's own answers ---------------------------------------------------------------
# Each of these is a value CMake would supply for a real target. Changing one changes both
# generated files together, which is the point of generating them from one place.
MISSION_NAME = "TempleOS-RV"
CFE_SRC_VERSION = "cfe v7.0.1+dev"
OSAL_VERSION = "osal v6.0.1+dev"
BUILD_CONFIG = "templeos-riscv64"
CPU_NAME = "CPU1"
CPU_ID = 1
SPACECRAFT_ID = 0x42
# Modules are TempleOS .BIN files; there are no shared objects on this target. Matches the
# OS_MODULE_FILE_EXTENSION decision recorded in tools/cfs/gen_osconfig.py.
MODULE_EXTENSION = ".BIN"
CORE_FILENAME = "core-cpu1.BIN"

# The two mount points this port has. /cf is the non-volatile side (the RedSea disk that
# `make tos` boots from); /ram is the volatile one.
NONVOL_MOUNT = "/cf"
RAMDISK_MOUNT = "/ram"
NONVOL_STARTUP_FILE = "/cf/cfe_es_startup.scr"

CDS_SIZE = 131072
RESET_AREA_SIZE = 170000
USER_RESERVED_SIZE = 1048576
RAMDISK_SECTOR_SIZE = 512
RAMDISK_TOTAL_SECTORS = 4096

# The cFE core modules this port has TRANSLATED. CFE_Config_SetupModuleVersions walks the
# config-id name table looking for MOD_SRCVER_<name> and only records a version for a module
# that appears in one of these lists, so listing a module this port does not have would
# manufacture a version for something that is not here.
CORE_MODULE_LIST = ["CFE_MSG", "CFE_RESOURCEID", "CFE_SBR", "CFE_CONFIG"]
STATIC_APP_LIST = []
PSP_MODULE_LIST = []

BUILD_ENVIRONMENT = [
    ("BUILDDATE", "20260930"),
    ("BUILDUSER", "templeos"),
    ("BUILDHOST", "riscv64"),
]
MODULE_VERSION_LIST = [("MISSION", "v1.0.0-templeos")] + [
    (m, "v7.0.1+dev") for m in CORE_MODULE_LIST
]


def c_str(s):
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


def emit_c():
    L = []
    L.append("/* GENERATED by tools/cfs/gen_target_config.py -- do not edit. */")
    L.append("/* CMake emits this per target in a real cFE build; see that file for why the")
    L.append("   values are port decisions rather than NASA's. */")
    L.append('#include "target_config.h"')
    L.append("")
    L.append("CFE_ConfigName_t CFE_CORE_MODULE_LIST[] = {")
    for m in CORE_MODULE_LIST:
        L.append("    {%s}," % c_str(m))
    L.append("    {NULL} /* terminator: the walk stops on a NULL Name */")
    L.append("};")
    L.append("CFE_ConfigName_t CFE_STATIC_APP_LIST[] = {")
    for m in STATIC_APP_LIST:
        L.append("    {%s}," % c_str(m))
    L.append("    {NULL}")
    L.append("};")
    L.append("CFE_StaticModuleLoadEntry_t CFE_PSP_MODULE_LIST[] = {")
    for m in PSP_MODULE_LIST:
        L.append("    {%s, NULL}," % c_str(m))
    L.append("    {NULL, NULL}")
    L.append("};")
    L.append("CFE_ConfigKeyValue_t CFE_BUILD_ENV_TABLE[] = {")
    for k, v in BUILD_ENVIRONMENT:
        L.append("    {%s, %s}," % (c_str(k), c_str(v)))
    L.append("    {NULL, NULL}")
    L.append("};")
    L.append("CFE_ConfigKeyValue_t CFE_MODULE_VERSION_TABLE[] = {")
    for k, v in MODULE_VERSION_LIST:
        L.append("    {%s, %s}," % (c_str(k), c_str(v)))
    L.append("    {NULL, NULL}")
    L.append("};")
    L.append("const Target_ObjectTable_t *const CFE_CORE_MODULE_OBJTAB[] = {NULL};")
    L.append("")
    L.append("Target_CfeConfigData GLOBAL_CFE_CONFIGDATA = {")
    L.append("    .CdsSize = %d," % CDS_SIZE)
    L.append("    .ResetAreaSize = %d," % RESET_AREA_SIZE)
    L.append("    .UserReservedSize = %d," % USER_RESERVED_SIZE)
    L.append("    .RamDiskSectorSize = %d," % RAMDISK_SECTOR_SIZE)
    L.append("    .RamDiskTotalSectors = %d," % RAMDISK_TOTAL_SECTORS)
    L.append("    .NonvolMountPoint = %s," % c_str(NONVOL_MOUNT))
    L.append("    .RamdiskMountPoint = %s," % c_str(RAMDISK_MOUNT))
    L.append("    .NonvolStartupFile = %s" % c_str(NONVOL_STARTUP_FILE))
    L.append("};")
    L.append("")
    L.append("Target_ConfigData GLOBAL_CONFIGDATA = {")
    L.append("    .MissionName = %s," % c_str(MISSION_NAME))
    L.append("    .CfeVersion = %s," % c_str(CFE_SRC_VERSION))
    L.append("    .OsalVersion = %s," % c_str(OSAL_VERSION))
    L.append("    .Config = %s," % c_str(BUILD_CONFIG))
    L.append("    .Default_CpuName = %s," % c_str(CPU_NAME))
    L.append("    .Default_CpuId = %d," % CPU_ID)
    L.append("    .Default_SpacecraftId = %d," % SPACECRAFT_ID)
    L.append("    .Default_ModuleExtension = %s," % c_str(MODULE_EXTENSION))
    L.append("    .Default_CoreFilename = %s," % c_str(CORE_FILENAME))
    L.append("    .CfeConfig = &GLOBAL_CFE_CONFIGDATA,")
    L.append("    .PspModuleList = CFE_PSP_MODULE_LIST,")
    L.append("    .BuildEnvironment = CFE_BUILD_ENV_TABLE,")
    L.append("    .ModuleVersionList = CFE_MODULE_VERSION_TABLE,")
    L.append("    .CoreModuleList = CFE_CORE_MODULE_LIST,")
    L.append("    .CoreObjectTable = CFE_CORE_MODULE_OBJTAB,")
    L.append("    .StaticAppList = CFE_STATIC_APP_LIST,")
    L.append("    /* No EDS in this configuration: CFE_EDS_ENABLED is off, so these stay NULL")
    L.append("       and CFE_Config_Init stores NULL object pointers for them. */")
    L.append("    .EdsDb = NULL,")
    L.append("    .SbIntfDb = NULL,")
    L.append("    .TaAffinityTable = NULL")
    L.append("};")
    return "\n".join(L) + "\n"


def emit_hc():
    L = []
    L.append("// GENERATED by tools/cfs/gen_target_config.py -- do not edit.")
    L.append("//")
    L.append("// The HolyC half of cFE's build-generated target configuration, from the SAME values")
    L.append("// as the C half, so the two sides of the differential oracle cannot disagree about a")
    L.append("// mount point or a module list and leave the transcript to discover it somewhere far")
    L.append("// away. See the generator for why these values are port decisions.")
    L.append("#ifndef CFE_TARGET_CONFIG_HC")
    L.append("#define CFE_TARGET_CONFIG_HC")
    L.append("")
    L.append("class CFE_ConfigName_t")
    L.append("{")
    L.append("  U8 *Name;")
    L.append("};")
    L.append("")
    L.append("class CFE_ConfigKeyValue_t")
    L.append("{")
    L.append("  U8 *Key;")
    L.append("  U8 *Value;")
    L.append("};")
    L.append("")
    L.append("class CFE_StaticModuleLoadEntry_t")
    L.append("{")
    L.append("  U8 *Name;")
    L.append("  U8 *Api;")
    L.append("};")
    L.append("")
    L.append("class Target_CfeConfigData")
    L.append("{")
    L.append("  U0 (*System1HzISR)();")
    L.append("  U0 (*SystemMain)();")
    L.append("  U0 (*SystemNotify)();")
    L.append("  U32 CdsSize;")
    L.append("  U32 ResetAreaSize;")
    L.append("  U32 UserReservedSize;")
    L.append("  U32 RamDiskSectorSize;")
    L.append("  U32 RamDiskTotalSectors;")
    # Five uint32 after three function pointers land on offset 44, and the C compiler aligns the
    # pointer that follows to 48. HolyC classes are packed, so the four bytes have to be written.
    L.append("  U8 _pad0[4]; // C pads here; HolyC packs. See tools/cfs/check_padding.py")
    L.append("  U8 *NonvolMountPoint;")
    L.append("  U8 *RamdiskMountPoint;")
    L.append("  U8 *NonvolStartupFile;")
    L.append("};")
    L.append("")
    L.append("class Target_ConfigData")
    L.append("{")
    L.append("  U8 *MissionName;")
    L.append("  U8 *MissionVersion;")
    L.append("  U8 *CfeVersion;")
    L.append("  U8 *OsalVersion;")
    L.append("  U8 *Config;")
    L.append("  U8 *Date;")
    L.append("  U8 *User;")
    L.append("  U8 *Default_CpuName;")
    L.append("  U16 Default_CpuId;")
    L.append("  U16 Default_SpacecraftId;")
    # Two uint16 end at 68; the next pointer is aligned to 72 in C.
    L.append("  U8 _pad0[4]; // C pads here; HolyC packs. See tools/cfs/check_padding.py")
    L.append("  U8 *Default_ModuleExtension;")
    L.append("  U8 *Default_CoreFilename;")
    L.append("  Target_CfeConfigData *CfeConfig;")
    L.append("  CFE_StaticModuleLoadEntry_t *PspModuleList;")
    L.append("  CFE_ConfigKeyValue_t *BuildEnvironment;")
    L.append("  CFE_ConfigKeyValue_t *ModuleVersionList;")
    L.append("  CFE_ConfigName_t *CoreModuleList;")
    L.append("  U8 **CoreObjectTable;")
    L.append("  CFE_ConfigName_t *StaticAppList;")
    L.append("  U8 *EdsDb;")
    L.append("  U8 *DynamicEdsDb;")
    L.append("  U8 *SbIntfDb;")
    L.append("  U8 *TaAffinityTable;")
    L.append("};")
    L.append("")
    L.append("// HolyC has no designated initialisers and no initialised aggregates at file scope,")
    L.append("// so the tables are filled by a function the harness calls once. Same values, same")
    L.append("// order, same NULL terminators as the C.")
    n_core = len(CORE_MODULE_LIST) + 1
    n_app = len(STATIC_APP_LIST) + 1
    n_psp = len(PSP_MODULE_LIST) + 1
    n_env = len(BUILD_ENVIRONMENT) + 1
    n_ver = len(MODULE_VERSION_LIST) + 1
    L.append("CFE_ConfigName_t CFE_CORE_MODULE_LIST[%d];" % n_core)
    L.append("CFE_ConfigName_t CFE_STATIC_APP_LIST[%d];" % n_app)
    L.append("CFE_StaticModuleLoadEntry_t CFE_PSP_MODULE_LIST[%d];" % n_psp)
    L.append("CFE_ConfigKeyValue_t CFE_BUILD_ENV_TABLE[%d];" % n_env)
    L.append("CFE_ConfigKeyValue_t CFE_MODULE_VERSION_TABLE[%d];" % n_ver)
    L.append("Target_CfeConfigData GLOBAL_CFE_CONFIGDATA;")
    L.append("Target_ConfigData GLOBAL_CONFIGDATA;")
    L.append("")
    L.append("U0 CFE_TargetConfigInit()")
    L.append("{")
    for i, m in enumerate(CORE_MODULE_LIST):
        L.append('  CFE_CORE_MODULE_LIST[%d].Name = "%s";' % (i, m))
    L.append("  CFE_CORE_MODULE_LIST[%d].Name = NULL;" % len(CORE_MODULE_LIST))
    for i, m in enumerate(STATIC_APP_LIST):
        L.append('  CFE_STATIC_APP_LIST[%d].Name = "%s";' % (i, m))
    L.append("  CFE_STATIC_APP_LIST[%d].Name = NULL;" % len(STATIC_APP_LIST))
    for i, m in enumerate(PSP_MODULE_LIST):
        L.append('  CFE_PSP_MODULE_LIST[%d].Name = "%s";' % (i, m))
    L.append("  CFE_PSP_MODULE_LIST[%d].Name = NULL;" % len(PSP_MODULE_LIST))
    for i, (k, v) in enumerate(BUILD_ENVIRONMENT):
        L.append('  CFE_BUILD_ENV_TABLE[%d].Key = "%s";' % (i, k))
        L.append('  CFE_BUILD_ENV_TABLE[%d].Value = "%s";' % (i, v))
    L.append("  CFE_BUILD_ENV_TABLE[%d].Key = NULL;" % len(BUILD_ENVIRONMENT))
    for i, (k, v) in enumerate(MODULE_VERSION_LIST):
        L.append('  CFE_MODULE_VERSION_TABLE[%d].Key = "%s";' % (i, k))
        L.append('  CFE_MODULE_VERSION_TABLE[%d].Value = "%s";' % (i, v))
    L.append("  CFE_MODULE_VERSION_TABLE[%d].Key = NULL;" % len(MODULE_VERSION_LIST))
    L.append("  GLOBAL_CFE_CONFIGDATA.CdsSize = %d;" % CDS_SIZE)
    L.append("  GLOBAL_CFE_CONFIGDATA.ResetAreaSize = %d;" % RESET_AREA_SIZE)
    L.append("  GLOBAL_CFE_CONFIGDATA.UserReservedSize = %d;" % USER_RESERVED_SIZE)
    L.append("  GLOBAL_CFE_CONFIGDATA.RamDiskSectorSize = %d;" % RAMDISK_SECTOR_SIZE)
    L.append("  GLOBAL_CFE_CONFIGDATA.RamDiskTotalSectors = %d;" % RAMDISK_TOTAL_SECTORS)
    L.append('  GLOBAL_CFE_CONFIGDATA.NonvolMountPoint = "%s";' % NONVOL_MOUNT)
    L.append('  GLOBAL_CFE_CONFIGDATA.RamdiskMountPoint = "%s";' % RAMDISK_MOUNT)
    L.append('  GLOBAL_CFE_CONFIGDATA.NonvolStartupFile = "%s";' % NONVOL_STARTUP_FILE)
    L.append('  GLOBAL_CONFIGDATA.MissionName = "%s";' % MISSION_NAME)
    L.append('  GLOBAL_CONFIGDATA.CfeVersion = "%s";' % CFE_SRC_VERSION)
    L.append('  GLOBAL_CONFIGDATA.OsalVersion = "%s";' % OSAL_VERSION)
    L.append('  GLOBAL_CONFIGDATA.Config = "%s";' % BUILD_CONFIG)
    L.append('  GLOBAL_CONFIGDATA.Default_CpuName = "%s";' % CPU_NAME)
    L.append("  GLOBAL_CONFIGDATA.Default_CpuId = %d;" % CPU_ID)
    L.append("  GLOBAL_CONFIGDATA.Default_SpacecraftId = %d;" % SPACECRAFT_ID)
    L.append('  GLOBAL_CONFIGDATA.Default_ModuleExtension = "%s";' % MODULE_EXTENSION)
    L.append('  GLOBAL_CONFIGDATA.Default_CoreFilename = "%s";' % CORE_FILENAME)
    L.append("  GLOBAL_CONFIGDATA.CfeConfig = &GLOBAL_CFE_CONFIGDATA;")
    L.append("  GLOBAL_CONFIGDATA.PspModuleList = CFE_PSP_MODULE_LIST;")
    L.append("  GLOBAL_CONFIGDATA.BuildEnvironment = CFE_BUILD_ENV_TABLE;")
    L.append("  GLOBAL_CONFIGDATA.ModuleVersionList = CFE_MODULE_VERSION_TABLE;")
    L.append("  GLOBAL_CONFIGDATA.CoreModuleList = CFE_CORE_MODULE_LIST;")
    L.append("  GLOBAL_CONFIGDATA.CoreObjectTable = NULL;")
    L.append("  GLOBAL_CONFIGDATA.StaticAppList = CFE_STATIC_APP_LIST;")
    L.append("  // No EDS in this configuration (CFE_EDS_ENABLED off), so these stay NULL.")
    L.append("  GLOBAL_CONFIGDATA.EdsDb = NULL;")
    L.append("  GLOBAL_CONFIGDATA.DynamicEdsDb = NULL;")
    L.append("  GLOBAL_CONFIGDATA.SbIntfDb = NULL;")
    L.append("  GLOBAL_CONFIGDATA.TaAffinityTable = NULL;")
    L.append("}")
    L.append("#endif")
    return "\n".join(L) + "\n"


def main(argv):
    if len(argv) != 1:
        print(__doc__)
        return 2
    outdir = argv[0]
    os.makedirs(outdir, exist_ok=True)
    cpath = os.path.join(outdir, "cfe_target_config.c")
    open(cpath, "w").write(emit_c())
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    hpath = os.path.join(root, "Kernel", "Cfs", "cfe", "cfe_target_config.HC")
    open(hpath, "w").write(emit_hc())
    print("cfs-targetcfg: %d core modules, %d build vars, %d module versions -> %s and %s"
          % (len(CORE_MODULE_LIST), len(BUILD_ENVIRONMENT), len(MODULE_VERSION_LIST),
             cpath, os.path.relpath(hpath, root)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
