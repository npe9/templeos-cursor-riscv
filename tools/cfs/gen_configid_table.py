#!/usr/bin/env python3
"""Do configure_file's job for the cFE config module, from NASA's own lists and templates.

cFE's config module is a key-value store whose KEY SET is generated at build time. Three files
come out of CMake that are not in the source tree:

    cfe_configid_offset.h       an enum, one entry per config id, plus _MAX
    cfe_config_ids.h            a #define per id
    cfe_configid_nametable.c    the id -> printable-name table

They are generated by modules/config/mission_build.cmake from NASA's own id lists and NASA's own
templates. THIS SCRIPT IS THAT CMAKE LOGIC RE-EXPRESSED, reading the same two list files and the
same two templates, so the data is NASA's and only the mechanism is ours. Nothing here is
invented; run it and diff against a real cFS build's generated files if you want to check.

    config_ids_base.cmake            14 ids, then MOD_SRCVER_<X> for every module in the mission
    tool/config_ids_dynamic.cmake     6 ids set from platform config

THE ONE MISSION-DEPENDENT PART, stated plainly: the MOD_SRCVER_ entries depend on which modules
a mission builds. We use MISSION_CORE_INTERFACES + MISSION_CORE_MODULES exactly as
cmake/mission_defaults.cmake lists them, with no mission apps, which is this port's
configuration. A mission with apps would have more ids and a larger _MAX. The C and the HolyC
sides are generated together from this one script, so they cannot disagree about the set.

    tools/cfs/gen_configid_table.py <outdir>
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CFE  = os.path.join(ROOT, "vendor", "cFE")

def cmake_list(path, varname):
    """Pull `list(APPEND <varname> A B C)` entries out of a .cmake file."""
    txt = open(path).read()
    txt = re.sub(r'#[^\n]*', '', txt)
    out = []
    for m in re.finditer(r'list\s*\(\s*APPEND\s+' + varname + r'\s+(.*?)\)', txt, re.S):
        for tok in m.group(1).split():
            if re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', tok):
                out.append(tok)
    return out

def mission_modules():
    txt = open(os.path.join(CFE, "cmake", "mission_defaults.cmake")).read()
    txt = re.sub(r'#[^\n]*', '', txt)
    names = []
    for var in ("MISSION_CORE_INTERFACES", "MISSION_CORE_MODULES"):
        m = re.search(r'set\s*\(\s*' + var + r'\s+(.*?)\)', txt, re.S)
        if not m:
            raise SystemExit(f"{var} not found in mission_defaults.cmake")
        for tok in re.findall(r'"?([A-Za-z_][A-Za-z0-9_]*)"?', m.group(1)):
            names.append(tok)
    return names

def config_ids():
    base = os.path.join(CFE, "modules", "config")
    ids = cmake_list(os.path.join(base, "config_ids_base.cmake"), "CFE_CONFIG_IDS")
    # the foreach in config_ids_base.cmake, with MISSION_APPS and MISSION_PSPMODULES empty
    ids += [f"MOD_SRCVER_{m.upper()}" for m in mission_modules()]
    ids += cmake_list(os.path.join(base, "tool", "config_ids_dynamic.cmake"), "CFE_CONFIG_IDS")
    return ids

def main(argv):
    if len(argv) != 1:
        print(__doc__)
        return 2
    outdir = argv[0]
    os.makedirs(outdir, exist_ok=True)
    ids = config_ids()
    macro_list = "".join(f"CFE_CONFIGID_DEFINE({i})\n" for i in ids)
    const_list = "".join(f"#define CFE_CONFIGID_{i} CFE_CONFIGID_FROM_OFFSET({i})\n" for i in ids)

    tmpl = os.path.join(CFE, "modules", "config", "cmake")
    for src, dst, subst in (
        ("cfe_configid_offset.h.in",   "cfe_configid_offset.h",   macro_list),
        ("cfe_configid_nametable.c.in","cfe_configid_nametable.c",macro_list),
        ("cfe_config_ids.h.in",        "cfe_config_ids.h",        const_list),
    ):
        body = open(os.path.join(tmpl, src)).read()
        body = body.replace("@GENERATED_ID_MACRO_LIST@", subst)
        body = body.replace("@GENERATED_CONSTANT_DEFINE_LIST@", subst)
        open(os.path.join(outdir, dst), "w").write(body)

    # The HolyC side of the same table, from the same list in the same order.
    hc = ['// GENERATED by tools/cfs/gen_configid_table.py -- do not edit.',
          '//',
          "// The HolyC half of what CMake's configure_file produces for the cFE config module:",
          '// the id offsets and the printable-name table, from NASA\'s config_ids_base.cmake and',
          '// tool/config_ids_dynamic.cmake. Generated beside the C so the two cannot disagree',
          '// about the id SET, which is the thing a differential transcript could not catch by',
          '// itself -- both sides would simply not have an id and nothing would print.',
          '#ifndef CFE_CONFIGID_OFFSET_HC',
          '#define CFE_CONFIGID_OFFSET_HC']
    for n, i in enumerate(ids):
        hc.append(f'#define CFE_ConfigIdOffset_{i} {n}')
    hc.append(f'#define CFE_ConfigIdOffset_MAX {len(ids)}')
    hc.append('')
    # The id macros, mirroring the generated cfe_config_ids.h one for one. The C's
    # CFE_CONFIGID_FROM_OFFSET(x) expands to
    #     CFE_CONFIGID_C(CFE_ResourceId_FromInteger(CFE_CONFIGID_BASE + CFE_ConfigIdOffset_##x))
    # and CFE_Config_OffsetToId is that expression as a function, with CFE_CONFIGID_C the
    # identity for the SIMPLE resourceid variant. cfe_config_init.c uses these by name
    # (CFE_CONFIGID_MISSION_NAME and so on), which is why they are generated rather than
    # written out in the translation: the id SET has to come from one place.
    hc.append('// The id macros of the generated cfe_config_ids.h. A #define is not evaluated')
    hc.append('// where it is written, so these may name CFE_Config_OffsetToId before')
    hc.append('// cfe_config.HC defines it.')
    for i in ids:
        hc.append(f'#define CFE_CONFIGID_{i} CFE_Config_OffsetToId(CFE_ConfigIdOffset_{i})')
    hc.append('')
    # NASA's table is an array of a ONE-MEMBER STRUCT, not an array of pointers:
    #     typedef struct CFE_Config_IdNameEntry { const char *Name; } CFE_Config_IdNameEntry_t;
    # Same storage and the same layout, but cfe_config_init.c walks it with a pointer and
    # `NamePtr->Name`, so flattening it to U8 *[] -- which this generator used to do -- makes
    # that function untranslatable as written. The class also brings the table under
    # check_structs.py and check_padding.py, which an anonymous pointer array never was.
    hc.append('class CFE_Config_IdNameEntry')
    hc.append('{')
    hc.append('  U8 *Name;')
    hc.append('};')
    hc.append('')
    hc.append('CFE_Config_IdNameEntry CFE_CONFIGID_NAMETABLE[CFE_ConfigIdOffset_MAX] = {')
    for i in ids:
        hc.append(f'  {{"{i}"}},')
    hc.append('};')
    hc.append('#endif')
    # The HolyC half lives with the other translated units, not in the build directory, because
    # the coverage checker and every reader look there. It is committed like a vendored
    # generated artifact, with this script named at the top of it.
    hcpath = os.path.join(ROOT, "Kernel", "Cfs", "cfe", "cfe_configid_offset.HC")
    open(hcpath, "w").write("\n".join(hc) + "\n")

    print(f"cfs-configid: {len(ids)} ids -> {outdir} and Kernel/Cfs/cfe/cfe_configid_offset.HC")
    return 0

if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
