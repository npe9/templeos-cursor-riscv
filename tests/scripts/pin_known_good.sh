#!/usr/bin/env bash
# Record or verify sha256 pins for last-good REPL / plat ELFs.
# Usage:
#   pin_known_good.sh              # pin default artifacts that exist
#   pin_known_good.sh --check      # verify current ELFs against pins
#   pin_known_good.sh --pin PATH   # pin one extra ELF (repeatable)
# See build/known-good/README.md and docs/OPS.md.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/build/known-good"
MODE=pin
EXTRA_ARGS=()

usage() {
  echo "usage: $0 [--check] [--pin PATH]..." >&2
  exit 2
}

while [ $# -gt 0 ]; do
  case "$1" in
    --check) MODE=check; shift ;;
    --pin)
      [ $# -ge 2 ] || usage
      EXTRA_ARGS[${#EXTRA_ARGS[@]}]="$2"
      shift 2
      ;;
    -h|--help) usage ;;
    *) usage ;;
  esac
done

mkdir -p "$OUT"

slug_of() {
  local p="$1"
  p="${p#./}"
  case "$p" in
    build/repl-holyc.elf|build/hc_repl.elf) echo "repl-holyc.elf" ;;
    bootstrap/repl.elf) echo "bootstrap-repl.elf" ;;
    build/kernels/*/plat.elf)
      basename "$(dirname "$p")" | sed 's/$/-plat.elf/'
      ;;
    *)
      basename "$p"
      ;;
  esac
}

sha_of() {
  local f="$1"
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$f" | awk '{print $1}'
  elif command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$f" | awk '{print $1}'
  else
    echo "error: need shasum or sha256sum" >&2
    exit 1
  fi
}

# Collect unique abs|rel pairs (order preserved).
PATH_LIST=""
add_path() {
  local rel="$1" abs
  case "$rel" in
    /*) abs="$rel" ;;
    *) abs="$ROOT/$rel" ;;
  esac
  case "$PATH_LIST" in
    *"|$abs|"*) return ;;
  esac
  PATH_LIST="${PATH_LIST}|${abs}|${rel}|"
  echo "${abs}|${rel}"
}

collect_paths() {
  add_path "build/repl-holyc.elf"
  add_path "build/hc_repl.elf"
  add_path "bootstrap/repl.elf"
  add_path "build/kernels/virt/plat.elf"
  local e
  for e in "${EXTRA_ARGS[@]+"${EXTRA_ARGS[@]}"}"; do
    add_path "$e"
  done
}

pin_one() {
  local abs="$1" rel="$2" slug pin hash
  if [ ! -f "$abs" ]; then
    echo "skip (missing): $rel"
    return 0
  fi
  if [ "$rel" = "build/hc_repl.elf" ] && [ -f "$ROOT/build/repl-holyc.elf" ]; then
    echo "skip (alias): $rel → use repl-holyc.elf"
    return 0
  fi
  slug=$(slug_of "$rel")
  hash=$(sha_of "$abs")
  pin="$OUT/${slug}.sha256"
  printf '%s  %s\n' "$hash" "$rel" >"$pin"
  echo "pinned $rel → ${slug}.sha256 ($hash)"
  printf '%s  %s\n' "$hash" "$rel" >>"$OUT/PIN.txt"
}

check_one() {
  local abs="$1" rel="$2" slug pin want got
  slug=$(slug_of "$rel")
  if [ "$rel" = "build/hc_repl.elf" ] && [ -f "$OUT/repl-holyc.elf.sha256" ]; then
    return 0
  fi
  pin="$OUT/${slug}.sha256"
  if [ ! -f "$pin" ]; then
    return 0
  fi
  want=$(awk '{print $1; exit}' "$pin")
  if [ ! -f "$abs" ]; then
    echo "FAIL missing ELF for pin $slug: $rel" >&2
    return 1
  fi
  got=$(sha_of "$abs")
  if [ "$got" != "$want" ]; then
    echo "FAIL $rel" >&2
    echo "  pinned:  $want" >&2
    echo "  current: $got" >&2
    return 1
  fi
  echo "OK $rel"
  return 0
}

rc=0
if [ "$MODE" = pin ]; then
  {
    echo "# known-good pins — generated by tests/scripts/pin_known_good.sh"
    echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || date -u)"
    echo
  } >"$OUT/PIN.txt"
  while IFS= read -r entry; do
    [ -n "$entry" ] || continue
    abs="${entry%%|*}"
    rel="${entry#*|}"
    pin_one "$abs" "$rel"
  done < <(collect_paths)
  echo "summary → $OUT/PIN.txt"
else
  checked=0
  while IFS= read -r entry; do
    [ -n "$entry" ] || continue
    abs="${entry%%|*}"
    rel="${entry#*|}"
    [ "$rel" = "build/hc_repl.elf" ] && continue
    slug=$(slug_of "$rel")
    pin="$OUT/${slug}.sha256"
    if [ -f "$pin" ]; then
      checked=$((checked + 1))
      check_one "$abs" "$rel" || rc=1
    fi
  done < <(collect_paths)
  for pin in "$OUT"/*.sha256; do
    [ -e "$pin" ] || continue
    rel=$(awk '{print $2; exit}' "$pin")
    [ -n "$rel" ] || continue
    abs="$ROOT/$rel"
    # Skip if already checked via defaults
    already=0
    while IFS= read -r entry; do
      r="${entry#*|}"
      if [ "$r" = "$rel" ]; then
        already=1
        break
      fi
    done < <(collect_paths)
    [ "$already" -eq 1 ] && continue
    checked=$((checked + 1))
    check_one "$abs" "$rel" || rc=1
  done
  if [ "$checked" -eq 0 ]; then
    echo "no pins in $OUT — run: make known-good-pin" >&2
    exit 1
  fi
fi

exit "$rc"
