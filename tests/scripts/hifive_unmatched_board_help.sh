#!/bin/bash
# Print HiFive Unmatched (FU740) board bring-up recipe + QEMU harness status.
# Nearest QEMU harness is -M sifive_u (FU540): same UART/CLINT/PLIC map.
set -eu
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
ELF="$ROOT/build/kernels/hifive_unmatched/plat.elf"
BIN="$ROOT/build/kernels/hifive_unmatched/plat.bin"
QEMU_ELF="$ROOT/build/kernels/hifive_unmatched/plat-qemu.elf"

echo "=== HiFive Unmatched (SiFive FU740-C000) ==="
echo "Defconfig: templeos-riscv/configs/hifive_unmatched_defconfig"
echo "Link:      tests/exec/harness/link_hifive_unmatched.ld @ 0x80200000 (board)"
echo "OpenOCD:   tests/openocd/hifive_unmatched_load_plat.tcl"
echo ""
echo "MMIO (FU740-C000; same map as FU540/sifive_u for what this kernel touches):"
echo "  UART0  0x10010000  SiFive UART (NOT 16550)  IRQ 39  115200 8N1"
echo "  UART1  0x10011000"
echo "  CLINT  0x02000000  rtcclk 1 MHz"
echo "  PLIC   0x0C000000"
echo "  PRCI   0x10000000   GPIO 0x10060000"
echo "  DDR    0x80000000+ 16 GiB (SPL+OpenSBI reserve ..0x80200000)"
echo ""
echo "JTAG (this is the part OpenOCD does not ship):"
echo "  JTAG comes out of the micro-USB: an on-board FT2232H (Dual RS232-HS, 0403:6010), channel A."
echo "  Channel B of the same chip is the UART0 console (115200). There is NO CP2105 on this board."
echo "  J18 is a 2-pin JTAG-MUX-SELECT jumper (no jumper = FT2232H; jumper = header J6)."
echo "  J6 is the external 2x5 JTAG header, Cortex-10 layout, 1.8 V LOGIC (VDD_1V8 on pin 1)."
echo "  Probe:  the on-board FT2232H via tests/openocd/hifive_unmatched_hart1.cfg (10 MHz, falling edge)."
echo "          Olimex ARM-USB-TINY-H is 2.0-5.0 V: NOT usable on the 1.8 V J6 header."
echo "  Config: tests/openocd/hifive_unmatched_hart1.cfg (measured); hifive_unmatched_ft2232h.cfg (4 harts)"
echo "  Known: a 1-5% per-DMI-scan error floor through the on-board TXB0104+mux path; examine/load"
echo "         over hundreds of ops hit it. See the cfg header and docs. Below 4 MHz DMI collapses."
echo "  Load:   tests/openocd/hifive_unmatched_load_plat.tcl"
echo ""
echo "Bring-up order:"
echo "  1. Power the board; stop at the U-Boot prompt so SPL+OpenSBI train DDR."
echo "     Loading before DDR is up writes into nothing and the first fetch traps."
echo "  2. openocd -f tests/openocd/hifive_unmatched.cfg -c \"init; scan_chain; shutdown\""
echo "     Expect a RISC-V TAP: 0x20000913. If you see 0x4ba00477 that is an ARM"
echo "     CoreSight DAP — the probe is wired to a different board."
echo "  3. make kernel-hifive-unmatched"
echo "  4. openocd -f tests/openocd/hifive_unmatched.cfg \\"
echo "             -f tests/openocd/hifive_unmatched_load_plat.tcl"
echo "  5. Console: CP2105 first port, 115200 8N1 — expect plat-smoke: PASS"
echo "  ENTRY  0x40200000"
echo "  FB     FB_PRESENT_SIMPLEFB; SIMPLEFB_BASE=0 until firmware XR24"
echo ""
if [ -f "$ELF" ]; then
  echo "Board artifact: $ELF ($(wc -c <"$ELF") bytes elf)"
  if [ -f "$BIN" ]; then
    echo "                $BIN ($(wc -c <"$BIN") bytes flat)"
  fi
else
  echo "Board artifact: missing — run: make kernel-hifive_unmatched"
fi
if [ -f "$QEMU_ELF" ]; then
  echo "QEMU harness:   $QEMU_ELF ($(wc -c <"$QEMU_ELF") bytes)"
else
  echo "QEMU harness:   missing — run: make kernel-hifive_unmatched (builds plat-qemu.elf)"
fi
echo ""
echo "Build / smoke:"
echo "  make kernel-hifive_unmatched"
echo "  make kernel-plat-hifive_unmatched-smoke   # -M virt + plat-qemu.elf"
echo "  make -C templeos-riscv qemu-args-hifive_unmatched"
echo ""
echo "QEMU harness (no native -M; UART/CLINT/PLIC bases match virt):"
echo "  qemu-system-riscv64 -M virt -m 128M -bios none \\"
echo "    -kernel build/kernels/hifive_unmatched/plat-qemu.elf -nographic"
echo "  # plat-qemu: REG_SHIFT=0 + DRAM@0x80000000; board plat keeps shift=2"
echo "  # Expect: plat-smoke: PASS"
echo ""
echo "U-Boot (UART0 already live):"
echo "  # Prefer ELF via tftp + bootelf, or flat bin + go:"
echo "  tftp \$loadaddr plat.bin"
echo "  go 0x40200000"
echo "  # Expect: plat-smoke: PASS"
echo ""
echo "OpenOCD / gdb (DDR already up):"
echo "  # source tests/openocd/hifive_unmatched_load_plat.tcl"
echo "  # or: load_image $ELF 0x40200000 elf ; reg pc 0x40200000 ; resume"
echo ""
echo "Sibling: Milk-V Mars → make kernel-milkv-mars-help (own defconfig/ld; do not edit this one)."
