#!/bin/bash
# Print the HiFive Unmatched (FU740) bring-up recipe + what is verified how.
# Full write-up with the measurements behind all of this: docs/HIFIVE_UNMATCHED.md
set -eu
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
KDIR="$ROOT/build/kernels/hifive_unmatched"

echo "=== HiFive Unmatched (SiFive FU740-C000) ==="
echo "Doc:       docs/HIFIVE_UNMATCHED.md   (measurements, not assertions)"
echo "Defconfig: templeos-riscv/configs/hifive_unmatched_defconfig"
echo "Link:      tests/exec/harness/link_hifive_unmatched.ld @ 0x80200000"
echo "OpenOCD:   tests/openocd/hifive_unmatched_hart1.cfg   <- USE THIS ONE (10 MHz, falling)"
echo "Preflight: tests/scripts/unmatched_jtag_floor_check.sh  <- RUN THIS FIRST"
echo "gdb:       tests/gdb/unmatched_takeover_openocd.gdb"
echo ""
echo "MMIO (FU740-C000; same map as the FU540/sifive_u for what this kernel touches):"
echo "  UART0  0x10010000  SiFive UART (NOT 16550: 32-bit TXDATA @ +0, FULL in bit 31)"
echo "  UART1  0x10011000"
echo "  CLINT  0x02000000  rtcclk 1 MHz        PLIC 0x0C000000   UART0 IRQ 39"
echo "  PRCI   0x10000000  <- NOT a UART. A byte store here writes CLOCK registers."
echo "  GPIO   0x10060000"
echo "  DDR    0x80000000+ 16 GiB"
echo ""
echo "HARTS — get this wrong and a working image looks dead:"
echo "  hart 0    S7,  rv64imac   NO F, NO D   misa=0x8000000000101105"
echo "  hart 1-4  U74, rv64imafdc              misa=0x800000000014112d"
echo "  The image is -march=rv64imafdc -mabi=lp64d, so it MUST run on a U74."
echo "  crt0.S is built -DBOOT_HARTID=1 for this board."
echo ""
echo "JTAG — the board has its OWN probe; you do not need an external one:"
echo "  On-board FT2232H behind the micro-USB. Enumerates as \"Dual RS232-HS\" 0403:6010,"
echo "  no USB serial, so macOS names the two ports by location:"
echo "    /dev/cu.usbserial-<loc>0   channel A = JTAG"
echo "    /dev/cu.usbserial-<loc>1   channel B = console, 115200 8N1"
echo "  (the LOWER of the pair is channel A; the numbers move with the physical port)"
echo "  tests/openocd/hifive_unmatched.cfg assumes an external Olimex ARM-USB-TINY-H on"
echo "  header J18 instead. That is not how this board is normally driven -- but it IS the"
echo "  fallback if the on-board link stays too noisy (see below)."
echo ""
echo "  *** adapter speed 10000 IS REQUIRED, NOT AN OPTIMISATION - AND IT IS STILL NOT ENOUGH ***"
echo "  Measured over 300+ alternating dmstatus/abstractcs/dmcontrol scans per setting:"
echo "    10 MHz falling  9 stray | 8 MHz falling 6 | 8 MHz rising 8 (+1 err) | 6 MHz falling 7"
echo "    3 MHz  OpenOCD ASSERTS (riscv-013.c:499 info->abits != 0)"
echo "    1-2 MHz  total collapse (0 of 30 reads parse)"
echo "  So there is a ~2-3% per-scan DMI corruption floor NO setting reaches zero on, and"
echo "  below ~4 MHz it is a collapse, not a floor. Slower is WORSE, and the original"
echo "  cfg advice -- 1 MHz to start, raise once proven -- was itself the bug."
echo ""
echo "  CURRENT HARDWARE STATUS - this is the blocker:"
echo "    works:     TAP scan (IDCODE 0x20000913); raw riscv dmi_read/dmi_write, 0/30 bad"
echo "    does NOT:  a full OpenOCD target examine, or a halt, does not reliably complete."
echo "    why:       those issue HUNDREDS of DMI ops and OpenOCD treats ONE bad status as"
echo "               FATAL with no retry. At a 2-3% floor they fail essentially every time."
echo "    Small probes LIE: 60-op probes look perfect. An earlier \"24/24 clean, found 5"
echo "    harts\" was true and still misleading, for exactly that reason."
echo ""
echo "  PREFLIGHT before you load anything (the failure mode is an assert mid-write):"
echo "    openocd -f tests/openocd/hifive_unmatched_hart1.cfg &"
echo "    tests/scripts/unmatched_jtag_floor_check.sh 300 0"
echo ""
echo "  Already ruled out, do not re-chase: macOS FTDI driver contention (identical under"
echo "  sudo after a clean detach), TDO sample edge (both measured), TRST/SRST levels,"
echo "  cable and host port (identical after swapping both)."
echo "  Fallback if the floor does not drop: the external Olimex ARM-USB-TINY-H on header"
echo "  J18 - an independent JTAG path bypassing the on-board FT2232H. Use the original"
echo "  hifive_unmatched.cfg for it, but at 10 MHz falling edge, NOT its 1 MHz default."
echo ""
echo "  dmstatus 0x30382 = allhalted|resumeack: a hart left halted by an earlier session"
echo "  whose resume never ran. Looks like a dead board; is not one."
echo ""
echo "Bring-up order:"
echo "  1. Power the board and let its OWN firmware run: ZSBL -> U-Boot SPL -> OpenSBI."
echo "     SPL is what trains DDR. Stop at the U-Boot prompt."
echo "     PREFER U-Boot over a booted Linux: one hart active, MMU off (satp=0), so gdb's"
echo "     load writes the physical addresses it claims to. Under Linux the MMU is on, the"
echo "     other three U74s keep running Linux after you steal one, and a getty owns the"
echo "     console. See docs/HIFIVE_UNMATCHED.md."
echo "     NEVER 'reset halt' a cold board: you would halt it before DDR exists."
echo "  2. openocd -f tests/openocd/hifive_unmatched_hart1.cfg"
echo "     Expect a RISC-V TAP 0x20000913. 0x4ba00477 is an ARM CoreSight DAP - wrong board."
echo "     Then run the floor check above BEFORE going further."
echo "  3. make kernel-hifive_unmatched   (and: make hello-unmatched)"
echo "  4. Start with the 745-byte asm payload, not the kernel - it separates"
echo "     'can we run code at all' from 'does the kernel work':"
echo "       riscv64-elf-gdb -q -batch \\"
echo "         -ex 'set \$tos_elf = \"$KDIR/hello.elf\"' \\"
echo "         -x tests/gdb/unmatched_takeover_openocd.gdb"
echo "     Expect on channel B: 'hello-unmatched: OK' (and mhartid / misa / fadd.d)."
echo "  5. Then the same command with plat.elf."
echo ""
echo "Why no U-Boot or OpenSBI build is needed: the board's own firmware does the one"
echo "thing we cannot (train DDR), and then we take the machine from it over JTAG. The"
echo "emulated rehearsal uses the OpenSBI that ships with QEMU."
echo ""
if [ -f "$KDIR/plat.elf" ]; then
  echo "Board artifacts:"
  echo "  $KDIR/plat.elf ($(wc -c <"$KDIR/plat.elf") bytes)"
  [ -f "$KDIR/plat.bin" ] && echo "  $KDIR/plat.bin ($(wc -c <"$KDIR/plat.bin") bytes flat)"
  [ -f "$KDIR/hello.elf" ] && echo "  $KDIR/hello.elf ($(wc -c <"$KDIR/hello.bin" 2>/dev/null || echo '?') bytes flat asm probe)"
else
  echo "Board artifacts: missing - run: make kernel-hifive_unmatched"
fi
echo ""
echo "Emulated verification (no hardware needed):"
echo "  make kernel-plat-hifive-unmatched-smoke      # real plat.bin @ 0x80200000, -M sifive_u, hart 1"
echo "  make kernel-plat-hifive-unmatched-controls   # the same gate broken 5 ways; each must fail"
echo "  make hello-unmatched-smoke                   # asm probe: OK on a U74, refuses on the S7"
echo "  make unmatched-takeover-smoke                # the SAME gdb takeover, OpenSBI in the chain"
echo "  make -C templeos-riscv qemu-args-hifive_unmatched"
echo ""
echo "  qemu-system-riscv64 -M sifive_u -smp 2 -bios none \\"
echo "    -device loader,file=$KDIR/plat.bin,addr=0x80200000 \\"
echo "    -device loader,addr=0x80200000,cpu-num=1 -nographic"
echo "  # -kernel cannot be used: on sifive_u it enters at DRAM base, so a 0x80200000"
echo "  # image would load and never be entered. cpu-num=1 because hart 0 has no FPU."
echo ""
echo "Sibling: Milk-V Mars -> make kernel-milkv-mars-help (own defconfig/ld; do not edit this one)."
