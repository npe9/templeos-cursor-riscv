#!/bin/bash
# Differential oracle for the NASA OSAL -> HolyC translation, PORTABLE LAYER.
#
# Same three properties as the cFS gate, for the same reasons -- each is blind to what the others
# catch: every NASA function must EXIST in the translation, the two transcripts must be
# byte-identical, and the blob must have no unresolved imports (an undefined prototype binds
# silently to the C runtime and the transcript never notices).
#
# WHY THIS RUNS WITH NO BACKEND. src/os/shared/src makes zero direct OS calls -- no pthread, no
# sem, no open/read/write, no malloc -- and dispatches to 128 OS_*_Impl functions a backend
# supplies. A recording stub satisfies those, and the transcript then asserts the dispatch and
# validation decisions, which is the entire contract of this layer. The hand-written TempleOS
# backend comes after, with this layer's seam as its specification.
set -u
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
HARNESS="$ROOT/tests/exec/harness"
OUTDIR="$ROOT/build/exec"
COMPILER="$ROOT/holyc-riscv"
OSAL="$ROOT/vendor/osal"
SHIM="$ROOT/vendor/shim"

# osconfig.h is GENERATED by CMake in a real build. Do that job from NASA's own template and
# defaults before anything below needs it -- these numbers are the array bounds the shared
# layer's object tables are sized by, so a hand-picked value would change the id arithmetic the
# translation is supposed to reproduce.
GENDIR="$ROOT/build/cfs"
python3 "$ROOT/tools/cfs/gen_osconfig.py" "$GENDIR" >/dev/null || {
  echo "FAIL osal-xlat — could not generate osconfig.h" >&2; exit 1; }

SRC_C="$OSAL/src/os/shared/src/osapi-errors.c
       $OSAL/src/os/shared/src/osapi-version.c"
SRC_HC="$ROOT/tests/exec/cases/osal_xlat_errors.hc"

GCC="${RISCV_GCC:-riscv64-unknown-elf-gcc}"
OBJCOPY="${RISCV_OBJCOPY:-riscv64-unknown-elf-objcopy}"
LD="${RISCV_LD:-riscv64-unknown-elf-ld}"
QEMU="${QEMU_SYSTEM:-qemu-system-riscv64}"
HOSTCC="${HOSTCC:-cc}"
TIMEOUT="timeout"; command -v gtimeout >/dev/null 2>&1 && TIMEOUT="gtimeout"

for t in "$GCC" "$OBJCOPY" "$LD" "$QEMU" "$HOSTCC"; do
  command -v "$t" >/dev/null 2>&1 || { echo "FAIL osal-xlat — missing $t" >&2; exit 1; }
done
# FAIL, not SKIP: a translation gate that quietly passes when the thing it compares against is
# absent is worse than no gate.
for f in $SRC_C; do
  [ -f "$f" ] || { echo "FAIL osal-xlat — OSAL sources absent ($f). Run tools/cfs/fetch.sh" >&2; exit 1; }
done

INC="-I$OSAL/src/os/inc -I$OSAL/src/os/shared/inc -I$OSAL/src/bsp/shared/inc -I$GENDIR -I$SHIM"

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT

# --- completeness ---------------------------------------------------------------------------
# shellcheck disable=SC2086
python3 "$ROOT/tools/cfs/check_coverage.py" $SRC_C || exit 1

# --- reference: NASA's C, unmodified ----------------------------------------------------------
# shellcheck disable=SC2086
if ! "$HOSTCC" -O0 -w $INC -o "$T/ref" "$ROOT/tests/osal/oracle_osal.c" $SRC_C 2>"$T/cc.log"; then
  echo "FAIL osal-xlat — the C reference did not build" >&2
  tail -12 "$T/cc.log" | sed 's/^/  /' >&2
  exit 1
fi
"$T/ref" > "$T/ref.txt" || { echo "FAIL osal-xlat — the C reference did not run" >&2; exit 1; }

# --- translation: HolyC for RISC-V -------------------------------------------------------------
mkdir -p "$OUTDIR"
if [ ! -f "$OUTDIR/crt0.o" ] || [ ! -f "$OUTDIR/oracle_out.o" ]; then
  "$GCC" -march=rv64imafdc -mabi=lp64d -mcmodel=medany -O2 -g -nostdlib -ffreestanding -fno-builtin \
    -c "$HARNESS/oracle_out.c" -o "$OUTDIR/oracle_out.o" || { echo "FAIL osal-xlat — harness" >&2; exit 1; }
  "$GCC" -march=rv64imafdc -mabi=lp64d -mcmodel=medany -O2 -g -nostdlib -ffreestanding -fno-builtin \
    -c "$HARNESS/crt0.S" -o "$OUTDIR/crt0.o" || { echo "FAIL osal-xlat — crt0" >&2; exit 1; }
fi
if ! HOLYC_INCLUDE_ROOT="$ROOT" "$COMPILER" "$SRC_HC" -o "$T/blob.bin" >/dev/null 2>&1; then
  echo "FAIL osal-xlat — HolyC compile error" >&2
  HOLYC_INCLUDE_ROOT="$ROOT" "$COMPILER" "$SRC_HC" -o "$T/blob.bin" 2>&1 | tail -20 >&2
  exit 1
fi
if [ -f "$ROOT/tools/blob_imports.py" ]; then
  unres=$(python3 "$ROOT/tools/blob_imports.py" "$T/blob.bin" 2>/dev/null)
  if [ -n "$unres" ]; then
    echo "FAIL osal-xlat — the blob has unresolved imports. A name the C runtime knows binds" >&2
    echo "                silently with the transcript still passing. Define or link these:" >&2
    echo "$unres" | sed 's/^/  /' >&2
    exit 1
  fi
fi
( cd "$T" && "$OBJCOPY" -I binary -O elf64-littleriscv blob.bin blob_in.o && \
  "$LD" -T "$HARNESS/link_exec.ld" -nostdlib --no-warn-mismatch -o k.elf \
    "$OUTDIR/crt0.o" "$OUTDIR/oracle_out.o" blob_in.o ) >/dev/null 2>&1 \
  || { echo "FAIL osal-xlat — link error" >&2; exit 1; }
$TIMEOUT 60 "$QEMU" -M virt -m 256M -bios none -kernel "$T/k.elf" -nographic </dev/null 2>&1 \
  | tr -d '\r' | grep -vE '^ORACLE|terminating on signal' > "$T/hc.txt"

# --- the property ------------------------------------------------------------------------------
if ! diff -u "$T/ref.txt" "$T/hc.txt" > "$T/diff.txt"; then
  echo "FAIL osal-xlat — transcripts differ (- = NASA's C, + = HolyC translation)" >&2
  head -30 "$T/diff.txt" | sed 's/^/  /' >&2
  exit 1
fi
n=$(grep -c '' "$T/ref.txt")
echo "osal-xlat: $n transcript lines identical between NASA's C and the HolyC translation"
echo "osal-xlat smoke: OK"
