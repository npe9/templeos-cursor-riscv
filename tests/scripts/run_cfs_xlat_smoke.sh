TIMEOUT="timeout"; command -v gtimeout >/dev/null 2>&1 && TIMEOUT="gtimeout"

for t in "$GCC" "$OBJCOPY" "$LD" "$QEMU" "$HOSTCC"; do
  command -v "$t" >/dev/null 2>&1 || { echo "FAIL cfs-xlat — missing $t" >&2; exit 1; }
