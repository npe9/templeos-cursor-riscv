     -I$CFE/modules/config/fsw/src -I$GENDIR
     -I$CFE/modules/time/fsw/src -I$CFE/modules/time/fsw/inc -I$CFE/modules/time/config
     -I$MD/fsw/src -I$MD/fsw/inc -I$MD/config
     -I$MM/fsw/src -I$MM/fsw/inc -I$MM/config
     -I$CS/fsw/src -I$CS/fsw/inc -I$CS/config
     -I$OSAL/src/os/inc -I$PSP/fsw/inc -I$CFE/cmake/sample_defs -I$CFE/cmake/target/inc -I$SHIM"

T="${CFS_XLAT_KEEP_DIR:-$(mktemp -d)}"
mkdir -p "$T"
[ -n "${CFS_XLAT_KEEP_DIR:-}" ] || trap 'rm -rf "$T"' EXIT

# --- the shared comment stripper's own control ------------------------------------------------
# Four gates used to carry their own strip_comments and three of them removed BLOCK comments
# first, which makes a `/*` inside a `//` comment a real opener. This driver has had
# `// Kernel/Cfs/**.HC` at line 562 for months; it was harmless only because no `*/` followed it,
# and the first exercise to add one blanked six thousand lines. check_variadic then compared 36
# declarations instead of 177 AND PASSED, because a declaration it cannot see cannot disagree.
# The only symptom was a count going down. This runs the three properties of the one surviving
# implementation.
python3 "$ROOT/tools/cfs/cfs_text.py" || exit 1

# --- completeness: every NASA function must EXIST in the translation -----------------------
# The transcript below compares behaviour, so it only sees functions the driver calls. A
# function nobody calls is invisible to it -- the C side links it from NASA's source, the HolyC
# side simply lacks it, and the diff stays empty. CFE_MSG_GetNextSequenceCount was missing that
# way for four commits while two commit messages called the module complete.
# shellcheck disable=SC2086
if ! python3 "$ROOT/tools/cfs/check_coverage.py" $SRC_C; then
  exit 1
fi

# --- signatures --------------------------------------------------------------------------------
# Coverage proves a NAME is present; it says nothing about arity or pointer-ness. Two generated
# OSAL semaphore signatures were wrong while passing coverage (OS_MutSemCreate lost `options`;
# OS_CondVarTimedWait took a relative delay where NASA takes an absolute wake time), and
# OS_StatusToString translated an int32 as I64. This makes that diff a command.
# shellcheck disable=SC2086
python3 "$ROOT/tools/cfs/check_signatures.py" $SRC_C || exit 1

# --- the backend seam ---------------------------------------------------------------------------
# The OS_*_Impl declarations are what the hand-written TempleOS backend will be built to, and
# neither check above can see a mistake in them: coverage looks at definitions in a .c, and
# check_signatures skips _Impl names and never compares return types at all. osapi_task.HC
# declared OS_TaskDetach_Impl returning U0 where NASA's header says int32.
python3 "$ROOT/tools/cfs/check_seam.py" || exit 1

# --- struct fields -----------------------------------------------------------------------------
# A translated class must have NASA's fields, in NASA's order. Nothing else here looks inside a
# struct: coverage compares names, check_signatures compares parameters, check_seam compares the
# seam, and the transcript sees a field only if something reads it. OS_SharedGlobalVars was
# missing CoresConfigured, and the mutex and rwlock records were missing last_owner and
# last_writer -- and with them the whole of the ownership tracking in Give/Take.
python3 "$ROOT/tools/cfs/check_structs.py" || exit 1

# --- struct LAYOUT -----------------------------------------------------------------------------
# check_structs above compares field names and order; this compares BYTES. HolyC classes are
# fully packed -- no inter-member padding, no alignment, no tail padding -- so wherever the C
# compiler aligns a member, the translation has to write the gap by hand. Nothing else could see
# it: both sides read the field they wrote, so the transcript agrees while the two structs
# describe different objects. Its first run found 17 of 53 classes wrong, including four at the
# wrong WIDTH -- OS_lock_mode_t is a C enum (4 bytes) that had been translated as I64, which made
# every token 24 bytes against NASA's 20.
python3 "$ROOT/tools/cfs/check_padding.py" || exit 1

# --- function-pointer MEMBERS -------------------------------------------------------------------
# The two checks above are both blind here by construction: check_structs compares field names and
# order, check_padding compares offsets and sizes, and a function pointer is eight bytes whatever
# it points at. check_signatures compares function PARAMETERS, not the types of class members. So
# CFE_TIME_SynchCallbackRegEntry_t.Ptr was `U0 (*Ptr)()` for three commits where NASA's typedef is
# `int32 (*)(void)`, with every gate green; the host C compiler refused it on the ORACLE's side the
# first time a driver assigned a real callback. This compares the RETURN KIND and the PARAMETER
# COUNT, and treats a member it cannot pair with NASA's as a FAILURE -- not finding the upstream
# declaration is the outcome that looks like success.
python3 "$ROOT/tools/cfs/check_fnptr_members.py" || exit 1

# --- the header inlines -------------------------------------------------------------------------
# check_coverage above compares NASA's .c files, and says so in its own comment: "`static inline`
# in a header is not our business". cFS puts real logic in header inlines -- cfe_tbl_regrec.h has
# twenty, cfe_es_resource.h twenty-four, 163 across the headers this port reads -- and until this
# gate existed every one of them was outside every gate. 92 were translated anyway, by whoever
# went and found them; the question a gate has to answer is what happens to the rest. What is
# REQUIRED is computed (the transitive closure of "a gated source calls it"), so gating a new .c
# makes its inlines required the same moment, with no list to remember to update.
python3 "$ROOT/tools/cfs/check_header_inlines.py" || exit 1

# --- the constants ------------------------------------------------------------------------------
# HolyC has no enum and no CMake, so the translation re-states hundreds of numbers by hand:
# event ids, message ids, bit masks, array bounds, error codes. Nothing above checks one. A
# wrong array BOUND shows up in check_padding because it sizes a struct; a wrong MESSAGE ID that
# nothing routes, or an event id no branch reaches, is invisible to every gate including the
# transcript. Its first run found five of ninety wrong in the EVS declarations -- three message
# ids, a buffer length, and CFE_MISSION_ES_MAX_APPLICATIONS confused with the PLATFORM one.
python3 "$ROOT/tools/cfs/check_constants.py" || exit 1

# --- is it even compiled? -----------------------------------------------------------------------
# Every gate above this line is driven from SRC_C, so each one measures the translation only
# where the C half names a counterpart. A .HC file that is complete, parses, and is included by
# NOBODY is invisible to all of them -- it cannot fail a gate, so the tree stays green while the
# thing it claims to translate is never run. cfe_sb_api.HC landed in exactly that state. This
# names the condition: reachable from a driver, or listed with a reason. Its own first run found
# two files I did not know were unwired, because the roots were hardcoded and there are three
# drivers, not two -- so it reads the roots out of the scripts now.
python3 "$ROOT/tools/cfs/check_wired.py" || exit 1
# --- the oracle must not define a global a GATED NASA source also defines ---------------
# A tentative definition in two translation units MERGES silently in C, so the link succeeds
# and nothing says which object the exercise is reading. Five of cFE's module state globals
# were in exactly that state -- CFE_ES_Global, CFE_SB_Global, CFE_EVS_Global, CFE_TBL_Global
# and CFE_TIME_Global, each with a comment promising it would go away when its source was
# gated. Every one of those sources is gated. A comment is not a gate; this is.
python3 "$ROOT/tools/cfs/check_oracle_globals.py" || exit 1

# --- the manifest ------------------------------------------------------------------------------
# What NASA's build contains per cFE module, and how much of it is gated -- parsed from each
# module's CMakeLists by if()-DEPTH, so a source inside a branch is reported with its guard
# rather than counted as if it were always built. The denominator here has been wrong before.
python3 "$ROOT/tools/cfs/check_manifest.py" --cfe || exit 1

# --- the variadic seam -------------------------------------------------------------------------
# A HolyC variadic function receives an implicit (argc, argv) pair and THE CALL SITE builds it,
# so a call compiled before the compiler has seen a `...` declaration packs nothing and the
# callee reads whatever the ABI left behind -- with no diagnostic at either end. Its first run
# found both shapes live at once: EVS_SendEvent called from four places above its own definition
# (which reached StrPrintNV as nargs=1, args=NULL and faulted on a load from address 0), and
# CFE_EVS_SendEvent declared NON-VARIADIC in cfe_ta_task.HC while cfe_evs.HC defines the variadic
# one. The second is invisible to check_signatures, which compares DEFINITIONS, and both
# definitions were right.
python3 "$ROOT/tools/cfs/check_variadic.py" || exit 1

# --- the printf conversions the formatter implements -------------------------------------------
# Kernel/Cfs/CfsStr.HC's StrPrintNV handles a fixed set of conversions and emits anything else
# LITERALLY -- deliberately, so an unhandled case shows up in a transcript. But that only holds
# for a format string some exercise reaches. MM arrived with "%p" in six of mm_utils.c's events,
# no earlier gated source used it, and an unhandled conversion DOES NOT CONSUME ITS ARGUMENT --
# so every argument after it shifts by one, the same way cfe_sb_api.c's "%zu" once did. This is
# the static half of the formatter's contract; the transcript below is the dynamic half, and
# neither sees what the other sees.
# shellcheck disable=SC2086
python3 "$ROOT/tools/cfs/check_formats.py" $SRC_C || exit 1

# --- the shared-data lock sites ----------------------------------------------------------------
# NASA writes CFE_ES_LockSharedData(__func__, __LINE__) and BOTH arguments reach the transcript
# when the mutex take fails. HolyC has neither, so the translation writes them out as literals
# -- which makes them constants, and a constant nobody compares drifts. With every ES line
# number written as 0, the FS mutex-failure probe printed Line=748 on NASA's side and Line=0 on
# the translation's; no other gate could see it, because a literal at a call site is neither a
# type nor a #define.
python3 "$ROOT/tools/cfs/check_lock_sites.py" || exit 1

# --- is the code actually THERE? --------------------------------------------------------------
# Every gate above this line reads SOURCE TEXT. A translated file can be included, parse
# cleanly, pass all of them, and contribute NOTHING to the binary -- which is
# docs/HOLYC_STRUCT_LIMITS.md #13, and it has now happened twice: cfe_time_api.HC lost all
# forty-six of its functions and cfe_es_task.HC lost all twenty-eight. Both times what noticed
# was luck. This opens the binary and asks for an address.
python3 "$ROOT/tools/cfs/check_in_blob.py" || exit 1

# --- a struct copy that loses twelve bytes of a twelve-byte struct ----------------------------
# docs/HOLYC_STRUCT_LIMITS.md #21: `arr[i] = s` and `*p = s` copy only the first EIGHT BYTES of
# a class, silently, where `var = s` and `ptr->member = s` are whole. cfe_es_perf.c's capture
# path lost the hardware timestamp from every performance log entry that way, and only the
# transcript saw it -- the layout, the signatures and the blob were all correct.
python3 "$ROOT/tools/cfs/check_struct_copy.py" || exit 1

# --- reference: NASA's C, unmodified -------------------------------------------------------
# shellcheck disable=SC2086
if ! "$HOSTCC" -O0 -w $INC -I"$ROOT/tests/cfs" -o "$T/ref" "$ROOT/tests/cfs/oracle_ccsdspri.c" $SRC_C "$GENDIR/cfe_configid_nametable.c" "$GENDIR/cfe_target_config.c" \
     "$GENDIR/cfe_platformcfg_tables.c" 2>"$T/cc.log"; then
  echo "FAIL cfs-xlat — the C reference did not build" >&2
  tail -40 "$T/cc.log" | sed 's/^/  /' >&2
  exit 1
fi
"$T/ref" > "$T/ref.txt" || { echo "FAIL cfs-xlat — the C reference did not run" >&2; exit 1; }

# --- translation: HolyC for RISC-V ----------------------------------------------------------
mkdir -p "$OUTDIR"
if [ ! -f "$OUTDIR/crt0.o" ] || [ ! -f "$OUTDIR/oracle_out.o" ]; then
  "$GCC" -march=rv64imafdc -mabi=lp64d -mcmodel=medany -O2 -g -nostdlib -ffreestanding -fno-builtin \
    -c "$HARNESS/oracle_out.c" -o "$OUTDIR/oracle_out.o" || { echo "FAIL cfs-xlat — harness" >&2; exit 1; }
  "$GCC" -march=rv64imafdc -mabi=lp64d -mcmodel=medany -O2 -g -nostdlib -ffreestanding -fno-builtin \
    -c "$HARNESS/crt0.S" -o "$OUTDIR/crt0.o" || { echo "FAIL cfs-xlat — crt0" >&2; exit 1; }
fi
if ! HOLYC_INCLUDE_ROOT="$ROOT" "$COMPILER" "$SRC_HC" -o "$T/blob.bin" >/dev/null 2>&1; then
  echo "FAIL cfs-xlat — HolyC compile error" >&2
  HOLYC_INCLUDE_ROOT="$ROOT" "$COMPILER" "$SRC_HC" -o "$T/blob.bin" 2>&1 | tail -20 >&2
  exit 1
fi
# NO UNRESOLVED IMPORTS. A HolyC prototype with no definition compiles clean and becomes an
# import for whoever links the blob to fill. Two outcomes, and only one of them is visible:
#   - a name the C runtime knows (bootstrap/holy_rt_names.h, 86 of them: Print, Abs, Free, Puts,
#     Exec...) BINDS SILENTLY to the runtime's version. Measured: declaring `I64 Abs(I64 x);`
#     without defining it and calling it leaves this gate reporting 88 identical lines and OK,
#     while the call runs C code instead of the port's.
#   - any other name prints "[unresolved import]" at runtime, which does reach the transcript.
# So the transcript covers the second case by accident and cannot see the first at all. The
# HOFYIMP1 trailer sees both (tools/blob_imports.py).
#
# This matters more the moment the translated units are included from the kernel rather than
# from this driver: cfe_msg_integrity.HC DECLARES CFE_TIME_GetTime and the body lives in the
# driver beside it, so the first kernel include without a definition is exactly this hazard.
if [ -f "$ROOT/tools/blob_imports.py" ]; then
  unres=$(python3 "$ROOT/tools/blob_imports.py" "$T/blob.bin" 2>/dev/null)
  if [ -n "$unres" ]; then
    echo "FAIL cfs-xlat — the blob has unresolved imports. Whoever links it fills these, and a" >&2
    echo "                name the C runtime knows binds silently with the transcript still" >&2
    echo "                passing. Define them or link them:" >&2
    echo "$unres" | sed 's/^/  /' >&2
    exit 1
  fi
fi
( cd "$T" && "$OBJCOPY" -I binary -O elf64-littleriscv blob.bin blob_in.o && \
  "$LD" -T "$HARNESS/link_exec.ld" -nostdlib --no-warn-mismatch -o k.elf \
    "$OUTDIR/crt0.o" "$OUTDIR/oracle_out.o" blob_in.o ) >/dev/null 2>&1 \
  || { echo "FAIL cfs-xlat — link error" >&2; exit 1; }
$TIMEOUT 60 "$QEMU" -M virt -m 256M -bios none -kernel "$T/k.elf" -nographic </dev/null 2>&1 \
  | tr -d '\r' | grep -vE '^ORACLE|terminating on signal' > "$T/hc.txt"

# --- the property -----------------------------------------------------------------------
if ! diff -u "$T/ref.txt" "$T/hc.txt" > "$T/diff.txt"; then
  echo "FAIL cfs-xlat — transcripts differ (- = NASA's C, + = HolyC translation)" >&2
  head -30 "$T/diff.txt" | sed 's/^/  /' >&2
  exit 1
fi
n=$(grep -c '' "$T/ref.txt")
echo "cfs-xlat: $n transcript lines identical between NASA's C and the HolyC translation"

# --- and it must not be SMALLER than it was -----------------------------------------------
# The diff above asserts that the two halves agree. It cannot notice that they agree about
# LESS than they used to: both sides change together, the diff stays empty, and the only
# evidence is this count. Removing a stub took it from 1,226 to 1,224 and left three committed
# probes asserting a zero against a zero -- see tests/cfs/transcript_floor.txt.
FLOOR_FILE="$ROOT/tests/cfs/transcript_floor.txt"
floor=$(head -1 "$FLOOR_FILE" 2>/dev/null)
case "$floor" in
  ''|*[!0-9]*)
    echo "FAIL cfs-xlat — $FLOOR_FILE does not start with a number, so the floor is not being" >&2
    echo "  applied at all, which is the shape it exists to refuse." >&2
    exit 1 ;;
esac
if [ "$n" -lt "$floor" ]; then
  echo "FAIL cfs-xlat — the transcript SHRANK: $n lines against a floor of $floor." >&2
  echo "  The two halves still agree, so the diff is empty; they agree about less. Something" >&2
  echo "  stopped printing. Find out what, and if it was deliberate -- a stub whose source is" >&2
  echo "  now gated usually is -- check what was WITNESSING it and move the witness before" >&2
  echo "  lowering the number. Three probes went dead that way once already." >&2
  exit 1
fi
if [ "$n" -gt "$floor" ]; then
  echo "cfs-xlat: the floor is $floor and can be raised to $n in the commit that earned it"
fi
echo "cfs-xlat smoke: OK"
