#!/bin/bash
# Differential oracle for the NASA cFS -> HolyC translation.
#
# Compiles the UNMODIFIED vendor/cFE/modules/msg/fsw/src/cfe_msg_ccsdspri.c natively and runs it;
# compiles the 1:1 HolyC translation for RISC-V and runs it under QEMU; requires the two
# transcripts to be IDENTICAL. That is the only way to tell a translation bug from a compiler bug,
# because from the outside they look the same.
set -u
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
HARNESS="$ROOT/tests/exec/harness"
OUTDIR="$ROOT/build/exec"
COMPILER="$ROOT/holyc-riscv"
CFE="$ROOT/vendor/cFE"
OSAL="$ROOT/vendor/osal"
SHIM="$ROOT/vendor/shim"
PSP="$ROOT/vendor/PSP"
# Every cFE source under test. Growing this list and the transcript together is how a translation
# advances: one file, one set of transcript lines, one diff.
SRC_C="$CFE/modules/msg/fsw/src/cfe_msg_ccsdspri.c
       $CFE/modules/msg/fsw/src/cfe_msg_msgid_v1.c
       $CFE/modules/sb/fsw/src/cfe_sb_msg_id_util.c
       $CFE/modules/msg/fsw/src/cfe_msg_sechdr_fc.c
       $CFE/modules/msg/fsw/src/cfe_msg_sechdr_time.c
       $CFE/modules/msg/fsw/src/cfe_msg_sechdr_checksum.c
       $CFE/modules/msg/fsw/src/cfe_msg_msgid_shared.c
       $CFE/modules/msg/fsw/src/cfe_msg_initdefaulthdr_pri.c
       $CFE/modules/msg/fsw/src/cfe_msg_init.c
       $CFE/modules/msg/fsw/src/cfe_msg_integrity.c
       $CFE/modules/msg/fsw/src/cfe_msg_objtab.c
       $CFE/modules/resourceid/fsw/src/cfe_resourceid_api.c
       $CFE/modules/resourceid/fsw/src/cfe_resourceid_objtab.c"
SRC_HC="$ROOT/tests/exec/cases/cfs_xlat_ccsdspri.hc"

GCC="${RISCV_GCC:-riscv64-unknown-elf-gcc}"
OBJCOPY="${RISCV_OBJCOPY:-riscv64-unknown-elf-objcopy}"
LD="${RISCV_LD:-riscv64-unknown-elf-ld}"
QEMU="${QEMU_SYSTEM:-qemu-system-riscv64}"
HOSTCC="${HOSTCC:-cc}"
TIMEOUT="timeout"; command -v gtimeout >/dev/null 2>&1 && TIMEOUT="gtimeout"

for t in "$GCC" "$OBJCOPY" "$LD" "$QEMU" "$HOSTCC"; do
  command -v "$t" >/dev/null 2>&1 || { echo "FAIL cfs-xlat — missing $t" >&2; exit 1; }
done
# FAIL, not SKIP: a translation gate that quietly passes when the thing it compares against is
# absent is worse than no gate.
for f in $SRC_C; do
  [ -f "$f" ] || { echo "FAIL cfs-xlat — NASA sources absent ($f). Run tools/cfs/fetch.sh" >&2; exit 1; }
done

# The include set it takes to compile ONE cFE file. This list IS a finding: cFE's headers are
# largely generated by CMake, so a port has to stand them up before a line of code is translated.
INC="-I$CFE/modules/core_api/fsw/inc -I$CFE/modules/core_api/config
     -I$CFE/modules/msg/fsw/inc -I$CFE/modules/msg/fsw/src -I$CFE/modules/msg/option_inc
     -I$CFE/modules/es/config -I$CFE/modules/es/fsw/inc
     -I$CFE/modules/sb/config -I$CFE/modules/sb/fsw/inc
     -I$CFE/modules/evs/config -I$CFE/modules/evs/fsw/inc
     -I$CFE/modules/tbl/config -I$CFE/modules/tbl/fsw/inc
     -I$CFE/modules/time/config -I$CFE/modules/time/fsw/inc
     -I$CFE/modules/fs/config -I$CFE/modules/fs/fsw/inc
     -I$CFE/modules/ta/config -I$CFE/modules/ta/fsw/inc
     -I$CFE/modules/resourceid/fsw/inc -I$CFE/modules/resourceid/config
     -I$CFE/modules/resourceid/option_inc
     -I$CFE/modules/config/fsw/inc
     -I$CFE/modules/core_private/fsw/inc -I$CFE/modules/core_private/config
     -I$OSAL/src/os/inc -I$PSP/fsw/inc -I$CFE/cmake/sample_defs -I$CFE/cmake/target/inc -I$SHIM"

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT

# --- reference: NASA's C, unmodified -------------------------------------------------------
# shellcheck disable=SC2086
if ! "$HOSTCC" -O0 -w $INC -I"$ROOT/tests/cfs" -o "$T/ref" "$ROOT/tests/cfs/oracle_ccsdspri.c" $SRC_C 2>"$T/cc.log"; then
  echo "FAIL cfs-xlat — the C reference did not build" >&2
  tail -12 "$T/cc.log" | sed 's/^/  /' >&2
  exit 1
fi
"$T/ref" > "$T/ref.txt" || { echo "FAIL cfs-xlat — the C reference did not run" >&2; exit 1; }

# --- translation: HolyC for RISC-V ----------------------------------------------------------
mkdir -p "$OUTDIR"
if [ ! -f "$OUTDIR/crt0.o" ] || [ ! -f "$OUTDIR/oracle_out.o" ]; then
  "$GCC" -march=rv64imafdc -mabi=lp64d -mcmodel=medany -O2 -g -nostdlib -ffreestanding -fno-builtin \
    -c "$HARNESS/oracle_out.c" -o "$OUTDIR/oracle_out.o" || { echo "FAIL cfs-xlat — harness" >&2; exit 1; }
  "$GCC" -march=rv64imafdc -mabi=lp64d -mcmodel=medany -O2 -g -nostdlib -ffreestanding -fno-builtin \
    -c "$HARNESS/crt0.S" -o "$OUTDIR/crt0.o" || { echo "FAIL cfs-xlat — crt0" >&2; exit 1; }
fi
if ! HOLYC_INCLUDE_ROOT="$ROOT" "$COMPILER" "$SRC_HC" -o "$T/blob.bin" >/dev/null 2>&1; then
  echo "FAIL cfs-xlat — HolyC compile error" >&2
  HOLYC_INCLUDE_ROOT="$ROOT" "$COMPILER" "$SRC_HC" -o "$T/blob.bin" 2>&1 | tail -20 >&2
  exit 1
fi
( cd "$T" && "$OBJCOPY" -I binary -O elf64-littleriscv blob.bin blob_in.o && \
  "$LD" -T "$HARNESS/link_exec.ld" -nostdlib --no-warn-mismatch -o k.elf \
    "$OUTDIR/crt0.o" "$OUTDIR/oracle_out.o" blob_in.o ) >/dev/null 2>&1 \
  || { echo "FAIL cfs-xlat — link error" >&2; exit 1; }
$TIMEOUT 60 "$QEMU" -M virt -m 256M -bios none -kernel "$T/k.elf" -nographic </dev/null 2>&1 \
  | tr -d '\r' | grep -vE 'import unresolved|^ORACLE|terminating on signal' > "$T/hc.txt"

# --- the property -----------------------------------------------------------------------
if ! diff -u "$T/ref.txt" "$T/hc.txt" > "$T/diff.txt"; then
  echo "FAIL cfs-xlat — transcripts differ (- = NASA's C, + = HolyC translation)" >&2
  head -30 "$T/diff.txt" | sed 's/^/  /' >&2
  exit 1
fi
n=$(grep -c '' "$T/ref.txt")
echo "cfs-xlat: $n transcript lines identical between NASA's C and the HolyC translation"
echo "cfs-xlat smoke: OK"
