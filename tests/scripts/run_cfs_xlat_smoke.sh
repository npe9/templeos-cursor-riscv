# NASA's own id lists and NASA's own templates, before the source list or the include path
# mention the results. The script also refreshes the HolyC half, so the two sides cannot drift
# apart about which ids exist -- a disagreement the transcript could not see, because a missing
# id simply prints nothing on both sides.
GENDIR="$ROOT/build/cfs"
python3 "$ROOT/tools/cfs/gen_configid_table.py" "$GENDIR" || {
  echo "FAIL cfs-xlat — could not generate the config id table" >&2; exit 1; }
