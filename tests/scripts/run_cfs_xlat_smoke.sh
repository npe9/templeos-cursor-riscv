# level up: fsw/src, fsw/inc and config.
MD="$ROOT/vendor/MD"
# The second. MM is the other memory app: MD only ever READS memory, MM pokes it, fills it,
# loads it from a file and dumps it to one -- so it needs the WRITE half of the simulated
# window MD established, plus a second simulated region for EEPROM.
MM="$ROOT/vendor/MM"
# The third. CS is the integrity app: it walks EEPROM, memory, the cFE core and the OS code
# segments, every registered table and every running app, CRCs each one and shouts when a
# checksum moves. It is the first app whose call graph is a CYCLE -- cs_utils calls into
# cs_compute and cs_table_processing and both call back -- so its sources gate in groups.
CS="$ROOT/vendor/CS"
